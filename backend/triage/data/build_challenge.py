"""Convert challenge_source.tsv to challenge.jsonl and check it against the splits.

Checks: categories, the exact audit_regression rows, temperature thresholds, exact and
near-duplicate (MiniLM cosine > 0.92) overlap with every row of train/val/test.
Writes challenge.jsonl and CHALLENGE_REPORT.md.

  HF_HUB_OFFLINE=1 backend/.venv/Scripts/python backend/triage/data/build_challenge.py
"""
from __future__ import annotations

import json
import random
from collections import Counter
from pathlib import Path

from build_dataset import (EMBED_MODEL, NEAR_DUP, RANK, SPLITS, apply_adjudication, embed,
                           norm_text, temp_floor, temperatures_c)

HERE = Path(__file__).resolve().parent
CATEGORIES = ("negation", "keyword_free_red", "indian_english", "typo_or_slang", "numeric_in_text",
              "multi_symptom", "benign_scary_word", "audit_regression")
AUDIT_ROWS = {
    ("No chest pain, no chills", "GREEN"),
    ("I don't have shortness of breath", "GREEN"),
    ("I cannot breathe properly", "RED"),
    ("I can’t breathe", "RED"),
    ("fever of 39", "RED"),
    ("My knee is a little red and swollen", "YELLOW"),
    ("fluid coming from my incision", "YELLOW"),
}


def main() -> None:
    rows = []
    for ln, line in enumerate((HERE / "challenge_source.tsv").read_text(encoding="utf-8").splitlines(), 1):
        if not line.strip() or line.startswith("#"):
            continue
        cat, label, surgery, text = line.split("\t")
        assert cat in CATEGORIES, (ln, cat)
        assert label in RANK, (ln, label)
        if surgery == "ANY":
            surgery = random.Random("surgery:" + text).choice(["TKA", "THA"])
        rows.append({"id": f"CH-{len(rows) + 1:03d}", "text": text, "label": label, "category": cat,
                     "surgery": surgery, "origin": "challenge", "generator": "claude-opus-5-5",
                     "written_after_splits": True})

    n_adj = apply_adjudication(rows)   # adjudication.tsv, see ADJUDICATION.md

    audit = {(r["text"], r["label"]) for r in rows if r["category"] == "audit_regression"}
    assert audit == AUDIT_ROWS, audit ^ AUDIT_ROWS
    assert sum(r["category"] == "audit_regression" for r in rows) == len(AUDIT_ROWS)
    assert any("’" in r["text"] for r in rows if r["category"] == "audit_regression")

    split_rows = [json.loads(l) for s in SPLITS
                  for l in open(HERE / "splits" / f"{s}.jsonl", encoding="utf-8")]
    split_norm = {norm_text(r["text"]): r for r in split_rows}
    exact = [r for r in rows if norm_text(r["text"]) in split_norm]

    e_ch = embed([r["text"] for r in rows])
    e_sp = embed([r["text"] for r in split_rows])
    sims = e_ch @ e_sp.T
    best = sims.argmax(1)

    rep = ["# Challenge set report\n",
           "Generated by `build_challenge.py`. The challenge set was written after the "
           "train/val/test splits were frozen; it must not be used for training or tuning.\n",
           f"Rows: **{len(rows)}**. Labels changed by `adjudication.tsv` (`ADJUDICATION.md`): "
           f"{n_adj}; `challenge_source.tsv` keeps the original labels.\n",
           "| category | rows | RED | YELLOW | GREEN |", "|---|---:|---:|---:|---:|"]
    for c in CATEGORIES:
        cc = Counter(r["label"] for r in rows if r["category"] == c)
        rep.append(f"| {c} | {sum(cc.values())} | {cc['RED']} | {cc['YELLOW']} | {cc['GREEN']} |")
    tot = Counter(r["label"] for r in rows)
    rep.append(f"| **all** | **{len(rows)}** | **{tot['RED']}** | **{tot['YELLOW']}** | **{tot['GREEN']}** |\n")

    under = [(r, temperatures_c(r["text"])) for r in rows
             if RANK[r["label"]] < RANK[temp_floor(temperatures_c(r["text"]))]]
    rep.append(f"Rows labelled below the temperature in their text: {len(under)}.")
    for r, cs in under:
        rep.append(f"- `{r['id']}` {r['label']} {cs}: {r['text']}")
    rep.append(f"\nExact (normalised) matches with train/val/test: **{len(exact)}**.")
    for r in exact:
        m = split_norm[norm_text(r["text"])]
        rep.append(f"- `{r['id']}` = `{m['id']}` ({m['split']}): {r['text']}")
    over = [(i, float(sims[i, best[i]])) for i in range(len(rows)) if sims[i, best[i]] > NEAR_DUP]
    rep.append(f"\nNear-duplicates of a split row ({EMBED_MODEL}, cosine > {NEAR_DUP}): **{len(over)}**. "
               f"Highest similarity to any split row: **{float(sims.max()):.3f}**; median of each "
               f"challenge row's closest match: {float(sorted(sims.max(1))[len(rows) // 2]):.3f}.")
    for i, s in over:
        m = split_rows[best[i]]
        rep.append(f"- {s:.3f} `{rows[i]['id']}` \"{rows[i]['text']}\" ~ `{m['id']}` ({m['split']}) \"{m['text']}\"")
    rep.append("\nClosest split row for the 10 most similar challenge rows:\n")
    rep.append("| cosine | challenge | closest split row |")
    rep.append("|---:|---|---|")
    for i in sorted(range(len(rows)), key=lambda i: -sims[i, best[i]])[:10]:
        m = split_rows[best[i]]
        rep.append(f"| {sims[i, best[i]]:.3f} | {rows[i]['text']} ({rows[i]['label']}) | "
                   f"{m['text']} ({m['label']}, {m['split']}) |")

    with open(HERE / "challenge.jsonl", "w", encoding="utf-8", newline="\n") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    (HERE / "CHALLENGE_REPORT.md").write_text("\n".join(rep) + "\n", encoding="utf-8")
    print("\n".join(rep))
    if under or exact or over:
        raise SystemExit("challenge set has problems; see report")


if __name__ == "__main__":
    main()
