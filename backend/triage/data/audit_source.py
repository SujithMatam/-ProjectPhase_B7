"""Audit the original triage_intent_{train,val,test}.jsonl exports.

Read-only over backend/triage/data/source/. Writes AUDIT.md next to this file.

Run:  python backend/triage/data/audit_source.py
"""
from __future__ import annotations

import json
import re
import statistics
from collections import Counter, defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE / "source"
SPLITS = ("train", "val", "test")

SURGERY_CODE = {
    "Total Knee Arthroplasty": "TKA",
    "Total Hip Arthroplasty": "THA",
    "Anterior Cruciate Ligament Reconstruction": "ACLR",
    "Rotator Cuff Repair": "RCR",
}


def load() -> dict[str, list[dict]]:
    out = {}
    for s in SPLITS:
        with open(SRC / f"triage_intent_{s}.jsonl", encoding="utf-8") as f:
            out[s] = [json.loads(line) for line in f if line.strip()]
    return out


def normalise(msg: str) -> str:
    """Collapse the generator's slot fillers so templates compare equal."""
    msg = re.sub(r"\b(Left|Right)\b", "{limb}", msg)
    msg = re.sub(r"\bday \d+\b", "day {day}", msg, flags=re.I)
    msg = re.sub(r"\bPost-Op Day \d+\b", "Post-Op Day {day}", msg)
    return msg.strip()


# Words that tie a sentence to a body region / procedure.
KNEE = re.compile(r"\bknee\b", re.I)
HIP = re.compile(r"\bhip\b", re.I)
LOWER_LIMB = re.compile(
    r"\b(knee|hip|calf|leg|shin|toes?|foot|ankle|crutch(es)?|walker|cane|walking stick|weight bearing|WBAT|heel slides?|cross my ankles)\b",
    re.I,
)
REPLACEMENT = re.compile(r"(replacement|artificial joint|new knee|new hip|replaced hip|implant|prosthe)", re.I)


def surgery_mismatch(code: str, msg: str) -> str | None:
    if code == "RCR" and LOWER_LIMB.search(msg):
        return "lower-limb wording for a shoulder (rotator cuff) repair"
    if code == "TKA" and HIP.search(msg):
        return "hip wording for a knee replacement"
    if code == "THA" and KNEE.search(msg) and not re.search(r"pillow between (my|your) knees", msg, re.I):
        return "knee wording for a hip replacement"
    if code == "ACLR" and HIP.search(msg):
        return "hip wording for an ACL reconstruction"
    if code in ("ACLR", "RCR") and REPLACEMENT.search(msg):
        return "joint-replacement wording for a non-replacement procedure"
    return None


def main() -> None:
    data = load()
    rows = [r for s in SPLITS for r in data[s]]
    lines: list[str] = []
    w = lines.append

    w("# Audit of the original triage dataset\n")
    w("Generated by `backend/triage/data/audit_source.py` from the files in `source/` "
      "(see `PROVENANCE.md`). Normalisation replaces `Left`/`Right` with `{limb}` and "
      "`day N` / `Post-Op Day N` with `{day}`.\n")

    # ---- 1. rows vs distinct sentences ---------------------------------
    w("## 1. Rows vs distinct sentences\n")
    w("| split | rows | distinct raw messages | distinct after normalising |")
    w("|---|---:|---:|---:|")
    norm_by_split = {}
    for s in SPLITS:
        raw = {r["user_message"] for r in data[s]}
        norm = {normalise(r["user_message"]) for r in data[s]}
        norm_by_split[s] = norm
        w(f"| {s} | {len(data[s])} | {len(raw)} | {len(norm)} |")
    all_raw = {r["user_message"] for r in rows}
    all_norm = {normalise(r["user_message"]) for r in rows}
    w(f"| **all** | **{len(rows)}** | **{len(all_raw)}** | **{len(all_norm)}** |\n")
    per_norm = Counter(normalise(r["user_message"]) for r in rows)
    w(f"Every normalised sentence is repeated on average {len(rows)/len(all_norm):.1f} times "
      f"(min {min(per_norm.values())}, max {max(per_norm.values())}). "
      f"The generator (`dataset_builder.py`) has 22 scenarios x 3 templates = 66 templates; "
      f"{len(all_norm)} of them appear in the data.\n")

    # ---- 2. overlap ------------------------------------------------------
    w("## 2. Overlap between splits (normalised sentences)\n")
    w("| pair | shared sentences | share of the second split's distinct sentences | rows in second split whose sentence is also in the first |")
    w("|---|---:|---:|---:|")
    for a, b in (("train", "test"), ("train", "val"), ("val", "test")):
        shared = norm_by_split[a] & norm_by_split[b]
        rows_b = sum(1 for r in data[b] if normalise(r["user_message"]) in norm_by_split[a])
        w(f"| {a} / {b} | {len(shared)} | {len(shared)}/{len(norm_by_split[b])} "
          f"({100*len(shared)/len(norm_by_split[b]):.0f}%) | {rows_b}/{len(data[b])} "
          f"({100*rows_b/len(data[b]):.0f}%) |")
    unseen_test = norm_by_split["test"] - norm_by_split["train"]
    w(f"\nTest sentences never seen in train: {len(unseen_test)}.")
    if unseen_test:
        for u in sorted(unseen_test):
            w(f"- `{u}`")
    w("\nThe original splits are therefore a memorisation test, not a generalisation test.\n")

    # ---- 3. surgery / symptom mismatch ---------------------------------
    w("## 3. Surgery / symptom mismatches\n")
    w("`surgery_type` is drawn at random independently of the template, so sentences about a "
      "hip, knee, calf or crutches are attached to procedures where they make no sense.\n")
    mism = []
    for r in rows:
        code = SURGERY_CODE[r["surgery_type"]]
        why = surgery_mismatch(code, r["user_message"])
        if why:
            mism.append((r, code, why))
    w(f"Rows flagged: **{len(mism)} / {len(rows)} ({100*len(mism)/len(rows):.0f}%)**.\n")
    by_code = Counter(c for _, c, _ in mism)
    tot_code = Counter(SURGERY_CODE[r["surgery_type"]] for r in rows)
    w("| surgery | rows | flagged |")
    w("|---|---:|---:|")
    for c in ("TKA", "THA", "ACLR", "RCR"):
        w(f"| {c} | {tot_code[c]} | {by_code[c]} |")
    w("")
    by_reason = Counter(why for _, _, why in mism)
    w("| reason | rows |")
    w("|---|---:|")
    for why, n in by_reason.most_common():
        w(f"| {why} | {n} |")
    w("\nExamples (one per normalised sentence/surgery pair, first 12):\n")
    seen = set()
    for r, code, why in mism:
        key = (normalise(r["user_message"]), code)
        if key in seen:
            continue
        seen.add(key)
        if len(seen) > 12:
            break
        w(f"- {code} ({r['split']}): \"{r['user_message']}\" - {why}")
    w("\nSurgery types ACLR and RCR make up "
      f"{tot_code['ACLR'] + tot_code['RCR']} rows; nearly all templates were written for hip/knee replacement. "
      "The new dataset only uses TKA and THA.\n")

    # ---- 4. temperature by label ----------------------------------------
    w("## 4. `temperature_c` by label\n")
    w("| label | rows | min | median | max | rows >= 37.8 |")
    w("|---|---:|---:|---:|---:|---:|")
    by_label = defaultdict(list)
    for r in rows:
        if r["temperature_c"] is not None:
            by_label[r["expected_triage"]].append(r["temperature_c"])
    for lab in ("RED", "YELLOW", "GREEN"):
        t = by_label[lab]
        w(f"| {lab} | {len(t)} | {min(t)} | {statistics.median(t)} | {max(t)} | {sum(x >= 37.8 for x in t)} |")
    w("")
    w("By generator domain (from the `clinical_rationale` text):\n")
    w("| expected_triage | template family | rows | temperature range |")
    w("|---|---|---:|---|")
    fam = defaultdict(list)
    for r in rows:
        fam[(r["expected_triage"], r["clinical_rationale"][:60])].append(r["temperature_c"])
    for (lab, rat), t in sorted(fam.items(), key=lambda kv: (kv[0][0], -min(kv[1]))):
        w(f"| {lab} | {rat}... | {len(t)} | {min(t)}-{max(t)} |")
    w("")
    hot = [r for r in rows if r["temperature_c"] >= 38.5]
    warm = [r for r in rows if 37.8 <= r["temperature_c"] < 38.5]
    hot_fam = Counter(r["clinical_rationale"][:40] for r in hot)
    w(f"- Rows with temperature >= 38.5: {len(hot)}, all RED, all from "
      f"{len(hot_fam)} family ({', '.join(hot_fam)}...). It is the only family ever given a fever.")
    w(f"- Rows with 37.8 <= temperature < 38.5: {len(warm)}. The generator meant to give the "
      "\"Low-Grade Temperature\" (YELLOW) family 37.8-38.2, but tests `'Fever' in domain`, which is "
      "false, so that family got 36.5-37.2 like everything else.")
    w("- Every other row (the other 6 RED families included: DVT, PE, neurovascular, bleeding, "
      "compartment, dislocation) has 36.5-37.2.")
    w("- So `temperature_c` >= 38.5 is a perfect RED leak for one family and the field carries no "
      "information otherwise; the fever-question family has a normal stored temperature while its "
      "text talks about fever.")
    # message text vs temperature field contradictions
    contra = []
    for r in rows:
        m = re.search(r"(\d\d\.\d)\s*°?C", r["user_message"])
        if m and abs(float(m.group(1)) - r["temperature_c"]) >= 0.1:
            contra.append((r["user_message"], r["temperature_c"]))
    w(f"- Rows whose message states a temperature that differs from `temperature_c`: "
      f"{len(contra)} (e.g. \"{contra[0][0]}\" stored as {contra[0][1]}).\n" if contra else "")

    # ---- 5. label distribution ------------------------------------------
    w("## 5. Label distribution\n")
    w("| split | RED | YELLOW | GREEN |")
    w("|---|---:|---:|---:|")
    for s in SPLITS:
        c = Counter(r["expected_triage"] for r in data[s])
        w(f"| {s} | {c['RED']} | {c['YELLOW']} | {c['GREEN']} |")
    w("")
    lab_per_norm = defaultdict(set)
    for r in rows:
        lab_per_norm[normalise(r["user_message"])].add(r["expected_triage"])
    w(f"Normalised sentences with conflicting labels: "
      f"{sum(len(v) > 1 for v in lab_per_norm.values())} (labels come from the template's "
      "scenario, so they are consistent but inherit any scenario-level error; see "
      "`RELABEL_CHANGES.md`).\n")

    (HERE / "AUDIT.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
