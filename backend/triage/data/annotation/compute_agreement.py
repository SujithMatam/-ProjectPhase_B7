"""Agreement between the dataset labels and the blind second annotation.

Inputs (this folder): key.jsonl, second_labels.tsv, disagreement_rules.tsv (optional:
anon_id<TAB>guideline rule that decides the case, written by hand after reading the cases).
Outputs: ../ANNOTATION_AGREEMENT.md, ../ANNOTATION_DISAGREEMENTS.md, agreement.json

  python backend/triage/data/annotation/compute_agreement.py
"""
from __future__ import annotations

import json
import random
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
DATA = HERE.parent
LABELS = ("RED", "YELLOW", "GREEN")
RANK = {"GREEN": 0, "YELLOW": 1, "RED": 2}


def kappa(a: list[str], b: list[str], weighted: bool = False) -> float:
    n = len(a)
    pa, pb = Counter(a), Counter(b)
    if weighted:  # linear weights on the ordinal scale GREEN < YELLOW < RED
        dis = lambda x, y: abs(RANK[x] - RANK[y]) / 2
        obs = sum(dis(x, y) for x, y in zip(a, b)) / n
        exp = sum(pa[x] * pb[y] * dis(x, y) for x in LABELS for y in LABELS) / n ** 2
        return 1 - obs / exp if exp else 1.0
    po = sum(x == y for x, y in zip(a, b)) / n
    pe = sum(pa[l] * pb[l] for l in LABELS) / n ** 2
    return (po - pe) / (1 - pe) if pe < 1 else 1.0


def boot_ci(a, b, reps=2000, seed=7):
    rng = random.Random(seed)
    n = len(a)
    ks = []
    for _ in range(reps):
        idx = [rng.randrange(n) for _ in range(n)]
        ks.append(kappa([a[i] for i in idx], [b[i] for i in idx]))
    ks.sort()
    return ks[int(0.025 * reps)], ks[int(0.975 * reps) - 1]


def main() -> None:
    key = [json.loads(l) for l in open(HERE / "key.jsonl", encoding="utf-8")]
    second = {}
    for line in (HERE / "second_labels.tsv").read_text(encoding="utf-8").splitlines()[1:]:
        if line.strip():
            i, lab = line.split("\t")
            second[i.strip()] = lab.strip().upper()
    assert set(second) == {k["anon_id"] for k in key}, "id mismatch"
    assert all(v in LABELS for v in second.values())
    rules = {}
    rp = HERE / "disagreement_rules.tsv"
    if rp.exists():
        for line in rp.read_text(encoding="utf-8").splitlines()[1:]:
            if line.strip():
                i, r = line.split("\t", 1)
                rules[i.strip()] = r.strip()
    for k in key:
        k["second"] = second[k["anon_id"]]
    texts = {}
    for l in open(DATA / "annotation" / "blind_items.tsv", encoding="utf-8").read().splitlines()[1:]:
        i, t = l.split("\t", 1)
        texts[i] = t

    subsets = {"all": key, "split rows": [k for k in key if k["set"] == "split"],
               "challenge rows": [k for k in key if k["set"] == "challenge"]}
    res = {}
    out = ["# Annotation agreement\n",
           "Generated by `annotation/compute_agreement.py`. A second, independent annotation of a blind "
           "sample, compared with the **pre-adjudication** dataset labels (`annotation/key.jsonl`); "
           "disagreements are listed in `ANNOTATION_DISAGREEMENTS.md`. They have since been "
           "adjudicated (`ADJUDICATION.md`); these numbers are kept as measured before it.\n",
           "## Set-up\n",
           "- **Sample** (`annotation/build_annotation_sample.py`, seed 20261111): 300 rows from the main "
           "split (`splits/`), 100 per dataset label, at least one per scenario (all 31), drawn from "
           "train/val/test together; plus all 150 challenge rows. 450 items, shuffled, renamed "
           "T001-T450 (`annotation/key.jsonl` maps them back).",
           "- **Second annotator**: one claude-sonnet subagent. It was given only "
           "`LABELLING_GUIDELINE.md` and `annotation/blind_items.tsv` (opaque id + text): no labels, "
           "scenario names, tags, categories or split names. It was told not to open any other file or to "
           "label with code. Its labels: `annotation/second_labels.tsv`. Its tool calls, as it "
           "reported them (the subagent transcript was not kept, so this is self-reported): read the "
           "guideline, read the blind items, write the labels, one shell check of the row count and ids.",
           "- **First annotation** = the dataset labels (written by claude-opus-5-5 together with the "
           "text). Both annotators are LLMs from the same vendor reading the same guideline, so agreement "
           "measures how reproducible the guideline is, not clinical correctness.",
           "- The split sample is balanced by label (100/100/100), not drawn at dataset prevalence, so its "
           "kappa is not the kappa of the full dataset.\n",
           "## Agreement\n",
           "| subset | n | agreement % | Cohen's kappa | 95% CI (bootstrap) | linear-weighted kappa |",
           "|---|---:|---:|---:|---|---:|"]
    for name, ks in subsets.items():
        a = [k["label"] for k in ks]
        b = [k["second"] for k in ks]
        po = sum(x == y for x, y in zip(a, b)) / len(a)
        kp = kappa(a, b)
        lo, hi = boot_ci(a, b)
        kw = kappa(a, b, weighted=True)
        res[name] = {"n": len(a), "agreement": round(po, 4), "kappa": round(kp, 4),
                     "kappa_ci95": [round(lo, 4), round(hi, 4)], "weighted_kappa": round(kw, 4)}
        out.append(f"| {name} | {len(a)} | {100 * po:.1f} | {kp:.3f} | {lo:.3f}-{hi:.3f} | {kw:.3f} |")
    out.append("")

    for name, ks in subsets.items():
        out.append(f"### Confusion matrix: {name} (rows = dataset label, columns = second annotator)\n")
        out.append("| dataset \\ second | RED | YELLOW | GREEN | total |")
        out.append("|---|---:|---:|---:|---:|")
        cm = Counter((k["label"], k["second"]) for k in ks)
        res[name]["confusion"] = {f"{x}->{y}": cm[(x, y)] for x in LABELS for y in LABELS}
        for x in LABELS:
            out.append(f"| {x} | " + " | ".join(str(cm[(x, y)]) for y in LABELS)
                       + f" | {sum(cm[(x, y)] for y in LABELS)} |")
        out.append("| total | " + " | ".join(str(sum(cm[(x, y)] for x in LABELS)) for y in LABELS)
                   + f" | {len(ks)} |\n")

    dis = [k for k in key if k["label"] != k["second"]]
    pairs = Counter((k["label"], k["second"]) for k in dis)
    out.append("## Disagreements by direction (dataset -> second)\n")
    out.append("| dataset -> second | all | split rows | challenge rows | direction |")
    out.append("|---|---:|---:|---:|---|")
    for (x, y), c in sorted(pairs.items(), key=lambda p: (-p[1], p[0])):
        cs = sum(1 for k in dis if (k["label"], k["second"]) == (x, y) and k["set"] == "split")
        out.append(f"| {x} -> {y} | {c} | {cs} | {c - cs} | "
                   f"{'second is higher' if RANK[y] > RANK[x] else 'second is lower'} |")
    up = sum(RANK[k["second"]] > RANK[k["label"]] for k in dis)
    out.append(f"\nTotal {len(dis)}: second annotator higher in {up}, lower in {len(dis) - up}. "
               f"RED<->GREEN: {sum({k['label'], k['second']} == {'RED', 'GREEN'} for k in dis)}.\n")

    out.append("## Agreement by group\n")
    out.append("| set | group | n | agree | disagreements (dataset->second) |")
    out.append("|---|---|---:|---:|---|")
    for st in ("split", "challenge"):
        groups = sorted({k["group"] for k in key if k["set"] == st})
        for g in groups:
            ks = [k for k in key if k["set"] == st and k["group"] == g]
            d = Counter(f"{k['label'][0]}->{k['second'][0]}" for k in ks if k["label"] != k["second"])
            out.append(f"| {st} | {g} | {len(ks)} | {sum(k['label'] == k['second'] for k in ks)} | "
                       + (", ".join(f"{p} x{c}" for p, c in sorted(d.items())) or "-") + " |")
    out.append("")
    by_split = Counter((k["split"], k["label"] == k["second"]) for k in key if k["set"] == "split")
    out.append("Split rows by split: " + ", ".join(
        f"{s} {by_split[(s, True)]}/{by_split[(s, True)] + by_split[(s, False)]}" for s in ("train", "val", "test")) + ".\n")
    out.append("## Reading these numbers\n")
    out.append("- Agreement this high is best read as an **upper bound**. Most messages were written to "
               "fit the guideline, so they are prototypical cases, and both annotators are Claude models "
               "sharing priors. Agreement shows the guideline can be reproduced by a second reader; it "
               "does not show that the labels are clinically right. Clinician review is still missing.")
    out.append("- Every disagreement is on the YELLOW/GREEN boundary. None involves RED. They cluster "
               "on guideline gaps: a small amount of blood on the dressing, a clinician-reassured "
               "symptom that is still present (rule 3), a loose suture end, and a benign explanation "
               "offered by the patient (rule 7). See `ANNOTATION_DISAGREEMENTS.md`.")
    out.append("- The bootstrap intervals are wide on the challenge subset (150 rows): a few disagreements "
               "more or fewer would move kappa by several points.\n")
    res["disagreements"] = len(dis)
    res["pairs"] = {f"{x}->{y}": c for (x, y), c in pairs.items()}
    (DATA / "ANNOTATION_AGREEMENT.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    (HERE / "agreement.json").write_text(json.dumps(res, indent=2) + "\n", encoding="utf-8")

    d = ["# Annotation disagreements\n",
         "Generated by `annotation/compute_agreement.py` from `annotation/key.jsonl`, "
         "`annotation/second_labels.tsv` and the hand-written `annotation/disagreement_rules.tsv`. "
         "Every item where the blind second annotator's label differs from the dataset label. "
         "Labels shown are the pre-adjudication labels. Outcome: 5 of the 6 were changed to the "
         "second annotator's label and `CH-102` stayed YELLOW; see `ADJUDICATION.md`.\n",
         "The *deciding rule* column names the guideline passage that settles the case and the label "
         "that it points to on my reading. It was written by claude-opus-5-5, the same model that wrote "
         "the dataset labels, so treat it as a pointer for the adjudicator, not a ruling.\n",
         f"Total: {len(dis)} ({sum(k['set'] == 'split' for k in dis)} split rows, "
         f"{sum(k['set'] == 'challenge' for k in dis)} challenge rows).\n"]
    order = sorted(pairs, key=lambda p: (-(RANK[p[0]] != 1 and RANK[p[1]] != 1 and p[0] != p[1]), -pairs[p], p))
    for x, y in order:
        ks = sorted((k for k in dis if (k["label"], k["second"]) == (x, y)), key=lambda k: k["id"])
        d.append(f"## {x} -> {y} ({len(ks)})\n")
        d.append("| id | blind id | set / group | text | ours | second | deciding rule |")
        d.append("|---|---|---|---|---|---|---|")
        for k in ks:
            t = texts[k["anon_id"]].replace("|", "\\|")
            d.append(f"| `{k['id']}` | {k['anon_id']} | {k['split']} / {k['group']} | {t} | {k['label']} | "
                     f"{k['second']} | {rules.get(k['anon_id'], 'TODO')} |")
        d.append("")
    (DATA / "ANNOTATION_DISAGREEMENTS.md").write_text("\n".join(d) + "\n", encoding="utf-8")
    missing = [k["anon_id"] for k in dis if k["anon_id"] not in rules]
    print("\n".join(out))
    print(f"disagreements {len(dis)}; without a rule note: {len(missing)}")
    if missing:
        print("missing:", " ".join(missing))


if __name__ == "__main__":
    main()
