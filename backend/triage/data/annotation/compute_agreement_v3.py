"""Agreement between the challenge_v3 / integration-set labels and the blind second annotation.

Inputs (v3/): key.jsonl, second_labels.tsv, blind_items.tsv, annotator_tool_calls.md (optional).
Outputs: ../ANNOTATION_AGREEMENT_V3.md (agreement and kappa overall, per set and per category,
confusion matrices, every disagreement) and v3/agreement.json. No dataset label is changed.

  python backend/triage/data/annotation/compute_agreement_v3.py
"""
from __future__ import annotations

import json
from collections import Counter
from pathlib import Path

from compute_agreement import LABELS, RANK, _read_tsv, boot_ci, kappa

HERE = Path(__file__).resolve().parent
DATA = HERE.parent
D3 = HERE / "v3"


def main() -> None:
    key = [json.loads(l) for l in open(D3 / "key.jsonl", encoding="utf-8")]
    second = {i: v.upper() for i, v in _read_tsv(D3 / "second_labels.tsv").items()}
    assert set(second) == {k["anon_id"] for k in key}, "id mismatch"
    assert all(v in LABELS for v in second.values())
    texts = _read_tsv(D3 / "blind_items.tsv")
    for k in key:
        k["second"] = second[k["anon_id"]]
    subsets = {"all": key,
               "challenge_v3 (all)": [k for k in key if k["set"] == "challenge_v3"],
               **{g: [k for k in key if k["group"] == g] for g in sorted({k["group"] for k in key})}}
    res = {}
    out = ["# Annotation agreement: challenge_v3 and the integration set\n",
           "Generated by `annotation/compute_agreement_v3.py`. A blind second annotation of all 91 "
           "`challenge_v3.jsonl` rows and all 272 `integration_set.jsonl` rows, compared with the dataset "
           "labels. **No label was changed**; every disagreement is listed below.\n",
           "## Set-up (same method as `ANNOTATION_AGREEMENT_V2.md`)\n",
           "- **Items** (`annotation/build_annotation_sample_v3.py`, seed 20261114): the 363 texts of both "
           "sets pooled, shuffled and renamed C001-C363 (`annotation/v3/blind_items.tsv`), so the annotator "
           "could not tell the sets apart; `annotation/v3/key.jsonl` maps them back.",
           "- **Second annotator**: one fresh claude-sonnet subagent, given only `LABELLING_GUIDELINE.md` "
           "(v1.1) and the blind file. It was told not to open any other file, not to use git and not to "
           "label with code. Labels: `annotation/v3/second_labels.tsv`.",
           "- **First annotation** = the dataset labels (claude-opus-5-5). Both annotators are Claude "
           "models reading the same guideline: agreement measures how reproducible the guideline is on "
           "these messages, not clinical correctness.\n",
           "{{TOOLCALLS}}",
           "## Agreement\n",
           "| subset | n | dataset labels R/Y/G | second R/Y/G | agreement % | Cohen's kappa | 95% CI (bootstrap) | linear-weighted kappa | RED vs non-RED agreement % |",
           "|---|---:|---|---|---:|---:|---|---:|---:|"]
    for name, ks in subsets.items():
        a = [k["label"] for k in ks]
        b = [k["second"] for k in ks]
        c, d = Counter(a), Counter(b)
        po = sum(x == y for x, y in zip(a, b)) / len(a)
        kp = kappa(a, b)
        lo, hi = boot_ci(a, b)
        kw = kappa(a, b, weighted=True)
        rb = sum((x == "RED") == (y == "RED") for x, y in zip(a, b)) / len(a)
        res[name] = {"n": len(a), "agreement": round(po, 4), "kappa": round(kp, 4),
                     "kappa_ci95": [round(lo, 4), round(hi, 4)], "weighted_kappa": round(kw, 4),
                     "red_binary_agreement": round(rb, 4)}
        out.append(f"| {'**all**' if name == 'all' else name} | {len(a)} | {c['RED']}/{c['YELLOW']}/{c['GREEN']} | "
                   f"{d['RED']}/{d['YELLOW']}/{d['GREEN']} | {100 * po:.1f} | {kp:.3f} | {lo:.3f}-{hi:.3f} | "
                   f"{kw:.3f} | {100 * rb:.1f} |")
    out.append("")
    for name in ("all", "challenge_v3 (all)", "integration"):
        ks = subsets[name]
        out.append(f"### Confusion matrix: {name} (rows = dataset label, columns = second annotator)\n")
        out.append("| dataset \\ second | RED | YELLOW | GREEN | total |")
        out.append("|---|---:|---:|---:|---:|")
        cm = Counter((k["label"], k["second"]) for k in ks)
        res[name]["confusion"] = {f"{x}->{y}": cm[(x, y)] for x in LABELS for y in LABELS}
        for x in LABELS:
            out.append(f"| {x} | " + " | ".join(str(cm[(x, y)]) for y in LABELS) + f" | {sum(cm[(x, y)] for y in LABELS)} |")
        out.append("")

    dis = [k for k in key if k["label"] != k["second"]]
    red_dis = [k for k in dis if "RED" in (k["label"], k["second"])]
    out.append(f"## Every disagreement ({len(dis)} of {len(key)}; {len(red_dis)} involve RED)\n")
    out.append("Labels are unchanged. Disagreements that involve RED change what counts as a RED miss or "
               "an over-triage in the v3 evaluation, so they are listed first; the evaluation is reported "
               "with the dataset labels, and `REPORT.md` notes how many of the over-triage / RED-miss rows "
               "are among them.\n")
    out.append("| id | blind id | group | text | dataset | second |")
    out.append("|---|---|---|---|---|---|")
    for k in sorted(dis, key=lambda k: ("RED" not in (k["label"], k["second"]), k["group"], k["id"])):
        t = texts[k["anon_id"]].replace("|", "\\|")
        out.append(f"| `{k['id']}` | {k['anon_id']} | {k['group']} | {t} | {k['label']} | {k['second']} |")
    up = sum(RANK[k["second"]] > RANK[k["label"]] for k in dis)
    out.append(f"\nSecond annotator higher on {up}, lower on {len(dis) - up}. "
               f"RED<->GREEN: {sum({k['label'], k['second']} == {'RED', 'GREEN'} for k in dis)}.")
    res["disagreements"] = len(dis)
    res["disagreements_involving_red"] = [k["id"] for k in red_dis]
    calls = D3 / "annotator_tool_calls.md"
    text = "\n".join(out) + "\n"
    text = text.replace("{{TOOLCALLS}}\n", (calls.read_text(encoding="utf-8").strip() + "\n\n") if calls.exists() else "")
    (DATA / "ANNOTATION_AGREEMENT_V3.md").write_text(text, encoding="utf-8")
    (D3 / "agreement.json").write_text(json.dumps(res, indent=2) + "\n", encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
