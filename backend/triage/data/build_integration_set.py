"""Build the integration set: integration_source.tsv -> integration_set.jsonl + INTEGRATION_SET_REPORT.md.

The integration set holds every patient message used in the backend test suites
(backend/test_*.py), labelled by LABELLING_GUIDELINE.md v1.1. It is for EVALUATION ONLY: never
train on it, tune on it or choose a threshold with it. Every v3 training row is near-duplicate
checked against it (build_train_v3.py), and challenge_v3 was checked against it too.

Checks done here:
  * every text occurs verbatim as (part of) a string constant in at least one backend/test_*.py
    (so no message is invented); the file:line of every occurrence is recorded in ``sources``;
  * no two rows are the same after normalisation;
  * no row is labelled below a temperature stated in its text.
``triaged_in_test_run`` (optional): with ``--capture DIR``, rows whose text reached
``classifier_triage.evaluate`` while the suites ran (capture_*.jsonl written by a scratch
instrumentation hook during the 2026-11-14 run) are flagged; without it the existing flags are kept.

  cd backend/triage/data && ../../.venv/Scripts/python build_integration_set.py [--capture DIR]
"""
from __future__ import annotations

import argparse
import ast
import hashlib
import json
from collections import Counter
from pathlib import Path

from build_dataset import RANK, norm_text, temp_floor, temperatures_c

HERE = Path(__file__).resolve().parent
BACKEND = HERE.parents[1]
OUT = HERE / "integration_set.jsonl"


def test_constants() -> list[tuple[str, int, str]]:
    """(file, line, string) for every string constant in backend/test_*.py, f-string parts included."""
    out = []
    for f in sorted(BACKEND.glob("test_*.py")):
        for node in ast.walk(ast.parse(f.read_text(encoding="utf-8"))):
            if isinstance(node, ast.Constant) and isinstance(node.value, str):
                out.append((f.name, node.lineno, node.value))
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--capture", type=Path, help="directory with capture_*.jsonl from a test run")
    a = ap.parse_args()

    rows = []
    for ln, line in enumerate((HERE / "integration_source.tsv").read_text(encoding="utf-8").splitlines(), 1):
        if not line.strip() or line.startswith("#"):
            continue
        label, text = line.split("\t")
        assert label in RANK, (ln, label)
        rows.append({"id": f"INT-{len(rows) + 1:03d}", "text": text.strip(), "label": label})

    consts = test_constants()
    missing = []
    for r in rows:
        src = [f"{f}:{l}" for f, l, s in consts if s.strip() == r["text"]]
        if not src:                      # e.g. part of a longer literal
            src = [f"{f}:{l}" for f, l, s in consts if r["text"] in s]
        if not src:
            missing.append(r["text"])
        r["sources"] = src
        r["source_files"] = sorted({s.split(":")[0] for s in src})
    assert not missing, f"not found in any backend/test_*.py: {missing}"
    norms = Counter(norm_text(r["text"]) for r in rows)
    dup = [t for t, n in norms.items() if n > 1]
    assert not dup, f"duplicate rows after normalisation: {dup}"
    under = [r["id"] for r in rows if RANK[r["label"]] < RANK[temp_floor(temperatures_c(r["text"]))]]
    assert not under, under

    old = {}
    if OUT.exists():
        old = {r["text"]: r.get("triaged_in_test_run") for r in map(json.loads, OUT.open(encoding="utf-8"))}
    captured = None
    if a.capture:
        captured = {json.loads(l)["text"] for f in sorted(a.capture.glob("capture_*.jsonl"))
                    for l in f.open(encoding="utf-8") if l.strip()}
    for r in rows:
        r["triaged_in_test_run"] = (r["text"] in captured) if captured is not None else old.get(r["text"])
        r.update(origin="integration", eval_only=True, labelled_by="claude-opus-5-5",
                 guideline="v1.1")

    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")

    lab = Counter(r["label"] for r in rows)
    per_file = Counter(fn for r in rows for fn in r["source_files"])
    trig = [r for r in rows if r["triaged_in_test_run"]]
    rep = ["# Integration set report\n",
           "Generated by `build_integration_set.py` from `integration_source.tsv`. "
           "`integration_set.jsonl` holds every patient message used in `backend/test_*.py`, labelled "
           "on 2026-11-14 by `LABELLING_GUIDELINE.md` v1.1 (claude-opus-5-5). **Evaluation only**: it is "
           "never trained on or used to choose a model, seed or threshold. The v3 training rows were "
           "near-duplicate-checked against it, and so was `challenge_v3.jsonl`.\n",
           "## How the messages were collected\n",
           "1. Static: every string constant in the 15 `backend/test_*.py` files that is passed to a "
           "conversation helper or a message parameter (`process`, `handle`, `dispatch`, `_converse`, "
           "`_interview`, `_run_interview`, `_handle`, `evaluate_turn`, `parametrize`, `user_message=`, ...) "
           "or stored in a list named like cases / messages / benchmarks / paraphrases.",
           "2. Runtime: the suites were run once (2026-11-14, `TRIAGE_MODE` unset, SMTP / DOCTOR_ALERT "
           "variables cleared, temporary patient database) with a scratch import hook that logged every "
           "text reaching `classifier_triage.evaluate`. This catches messages built at run time.",
           "3. The union was curated by hand. **Included**: anything a patient types that can be labelled "
           "on its own: questions, symptom or status statements (also short ones such as \"it really "
           "hurts a lot\"), off-topic chat and prompt-injection attempts. **Excluded**: bare answers with "
           "no clause or no symptom / question (numbers such as \"8\", \"my calf\", \"behind the knee\", "
           "yes / no / idk, \"80 degrees\", \"a cane\", \"paracetamol?\", \"dosage?\", \"pain check\", "
           "\"I missed it\"), agent replies, RAG documents, assertion and print text, patient ids, "
           "fixtures for helper functions (the drug-name list for `mentions_medication`), the copy of a "
           "message carrying the test marker `OLD-ASSESSMENT-MARKER-XYZ` (the clean copy is kept), and "
           "the parser / wiring fixtures in `backend/triage/test_*.py`.",
           "4. The builder checks that every text occurs verbatim in a test file (`sources` lists each "
           "file:line), that no two rows are the same after normalisation, and that no row is labelled "
           "below a temperature in its text.\n",
           "## Labelling notes (guideline v1.1)\n",
           "- Labels follow the guideline, not what a test expects. Where they differ the test is not "
           "changed; the difference is reported with the evaluation.",
           "- Unqualified pain or swelling of the operated joint (\"My knee is swollen.\", \"My knee "
           "hurts.\") is YELLOW: the guideline's \"symptom the patient is worried about that fits nowhere "
           "else\", and rule 6 when torn between GREEN and YELLOW. Mild, stable or settling soreness "
           "(\"My knee is sore.\", \"a mild 2 out of 10 ... about the same\") is GREEN.",
           "- Swelling or pain of the **calf / leg** (\"My calf is swollen.\", \"My leg is swollen and "
           "painful.\", \"severe calf pain and swelling\") is RED (clot-in-the-leg bullet). Sudden severe "
           "hip pain (\"8 out of 10 and came on suddenly\", hip) is RED (dislocation bullet); the same "
           "words for a knee are YELLOW.",
           "- \"Yellow fluid\" from the incision with no other description is RED: it sits between "
           "\"clear, pink or watery fluid\" (YELLOW) and \"pus\" (RED), and rule 6 picks the higher level. "
           "The two rows are listed so the choice is visible.",
           "- A missed dose of an unnamed pill is YELLOW (it may be the blood thinner); a missed "
           "paracetamol is GREEN.\n",
           f"## Contents\n",
           f"Rows: **{len(rows)}** (RED {lab['RED']} / YELLOW {lab['YELLOW']} / GREEN {lab['GREEN']}). "
           f"Rows whose text reached triage during the test run: {len(trig)}.\n",
           "| test file | rows that occur in it |", "|---|---:|"]
    for fn, n in sorted(per_file.items()):
        rep.append(f"| `{fn}` | {n} |")
    rep += ["", "RED rows:", ""]
    rep += [f"- `{r['id']}` {r['text']}" for r in rows if r["label"] == "RED"]
    rep.append(f"\nSHA-256 of `integration_set.jsonl`: `{hashlib.sha256(OUT.read_bytes()).hexdigest()}`")
    (HERE / "INTEGRATION_SET_REPORT.md").write_text("\n".join(rep) + "\n", encoding="utf-8")
    print("\n".join(rep))


if __name__ == "__main__":
    main()
