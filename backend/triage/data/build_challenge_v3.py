"""Convert challenge_v3_source.tsv to challenge_v3.jsonl and check it against every existing row.

challenge_v3 was written BEFORE any v3 training data and is frozen: never train or tune on it.
Categories: short_single_symptom (short messages with one symptom, mostly YELLOW / GREEN),
red_in_routine_question (RED signs inside an exercise / physio / diet question, with YELLOW and
GREEN contrasts), mixed (symptom + routine question, mostly YELLOW / GREEN).
Checks: categories, temperature thresholds, exact and near-duplicate (MiniLM cosine > 0.92)
overlap with every row of main train / val / test, the unseen-scenario split, challenge,
challenge_v2, the v2 training rows (train_v2_extra.jsonl) and the integration set.
Writes challenge_v3.jsonl and CHALLENGE_V3_REPORT.md (with the SHA-256 of the jsonl).

  cd backend/triage/data && HF_HUB_OFFLINE=1 ../../.venv/Scripts/python build_challenge_v3.py
"""
from __future__ import annotations

import hashlib
import json
import random
from collections import Counter
from pathlib import Path

import numpy as np

from build_dataset import EMBED_MODEL, NEAR_DUP, RANK, SPLITS, embed, norm_text, temp_floor, temperatures_c

HERE = Path(__file__).resolve().parent
CATEGORIES = ("short_single_symptom", "red_in_routine_question", "mixed")


def jl(path: Path, src: str) -> list[dict]:
    return [dict(json.loads(l), _src=src) for l in open(path, encoding="utf-8") if l.strip()]


def existing_rows() -> list[dict]:
    rows = [r for s in SPLITS for r in jl(HERE / "splits" / f"{s}.jsonl", f"main {s}")]
    seen = {r["id"] for r in rows}
    rows += [r for s in SPLITS for r in jl(HERE / "splits_unseen_scenario" / f"{s}.jsonl", f"unseen {s}")
             if r["id"] not in seen]
    rows += jl(HERE / "challenge.jsonl", "challenge")
    rows += jl(HERE / "challenge_v2.jsonl", "challenge_v2")
    rows += jl(HERE / "train_v2_extra.jsonl", "train_v2_extra")
    rows += jl(HERE / "integration_set.jsonl", "integration")
    return rows


def main() -> None:
    rows = []
    for ln, line in enumerate((HERE / "challenge_v3_source.tsv").read_text(encoding="utf-8").splitlines(), 1):
        if not line.strip() or line.startswith("#"):
            continue
        cat, label, pair, surgery, text = line.split("\t")
        assert cat in CATEGORIES, (ln, cat)
        assert label in RANK, (ln, label)
        assert pair == "-", (ln, pair)
        if surgery == "ANY":
            surgery = random.Random("surgery:" + text).choice(["TKA", "THA"])
        rows.append({"id": f"CH3-{len(rows) + 1:03d}", "text": text, "label": label, "category": cat,
                     "surgery": surgery, "origin": "challenge_v3", "generator": "claude-opus-5-5",
                     "written_before_v3_training": True})
    assert len({norm_text(r["text"]) for r in rows}) == len(rows), "duplicate inside challenge_v3"

    old = existing_rows()
    old_norm = {norm_text(r["text"]): r for r in old}
    exact = [r for r in rows if norm_text(r["text"]) in old_norm]
    e_new = embed([r["text"] for r in rows])
    e_old = embed([r["text"] for r in old])
    sims = e_new @ e_old.T
    best = sims.argmax(1)
    within = e_new @ e_new.T
    np.fill_diagonal(within, 0)

    src_counts = Counter(r["_src"] for r in old)
    rep = ["# Challenge set v3 report\n",
           "Generated by `build_challenge_v3.py`. `challenge_v3.jsonl` was written on 2026-11-14 "
           "**before** any v3 training data (`authored_v3/`) existed, labelled by "
           "`LABELLING_GUIDELINE.md` v1.1, and committed on its own. It must never be used for "
           "training or tuning; the v3 training rows were near-duplicate-checked against it.\n",
           "Target: the two failures in `backend/eval/reports/2026-11-14_main-post-merge-tests.md`: "
           "short symptom messages over-triaged to RED (\"My knee is swollen.\" p(RED) 0.72) and a RED "
           "sign inside a routine question called GREEN (\"I have severe calf pain and swelling, can I "
           "still do my exercises?\" p(RED) 0.011).\n",
           f"Rows: **{len(rows)}**.\n",
           "| category | rows | RED | YELLOW | GREEN |", "|---|---:|---:|---:|---:|"]
    for c in CATEGORIES:
        cc = Counter(r["label"] for r in rows if r["category"] == c)
        rep.append(f"| {c} | {sum(cc.values())} | {cc['RED']} | {cc['YELLOW']} | {cc['GREEN']} |")
    tot = Counter(r["label"] for r in rows)
    rep.append(f"| **all** | **{len(rows)}** | **{tot['RED']}** | **{tot['YELLOW']}** | **{tot['GREEN']}** |\n")

    under = [(r, temperatures_c(r["text"])) for r in rows
             if RANK[r["label"]] < RANK[temp_floor(temperatures_c(r["text"]))]]
    rep.append(f"Rows labelled below the temperature in their text: {len(under)}.")
    for r, cs in under:
        rep.append(f"- `{r['id']}` {r['label']} {cs}: {r['text']}")
    rep.append("\nChecked against (rows): " + ", ".join(f"{k} {v}" for k, v in src_counts.items()) + ".")
    rep.append(f"\nExact (normalised) matches: **{len(exact)}**.")
    over = [(i, float(sims[i, best[i]])) for i in range(len(rows)) if sims[i, best[i]] > NEAR_DUP]
    rep.append(f"\nNear-duplicates of an existing row ({EMBED_MODEL}, cosine > {NEAR_DUP}): "
               f"**{len(over)}**. Highest similarity to any existing row: **{float(sims.max()):.3f}**; "
               f"median of each row's closest match: {float(np.median(sims.max(1))):.3f}. "
               f"Highest similarity between two challenge_v3 rows: {float(within.max()):.3f}.")
    for i, s in over:
        m = old[best[i]]
        rep.append(f"- {s:.3f} `{rows[i]['id']}` \"{rows[i]['text']}\" ~ `{m['id']}` ({m['_src']}) \"{m['text']}\"")
    e_int = [k for k, r in enumerate(old) if r["_src"] == "integration"]
    s_int = sims[:, e_int].max(1)
    rep.append(f"\nAgainst the integration set only: highest cosine {float(s_int.max()):.3f}, "
               f"median closest {float(np.median(s_int)):.3f}.")
    rep.append("\nClosest existing row for the 12 most similar challenge_v3 rows:\n")
    rep.append("| cosine | challenge_v3 | closest existing row |")
    rep.append("|---:|---|---|")
    for i in sorted(range(len(rows)), key=lambda i: -sims[i, best[i]])[:12]:
        m = old[best[i]]
        rep.append(f"| {sims[i, best[i]]:.3f} | {rows[i]['text']} ({rows[i]['label']}) | "
                   f"{m['text']} ({m['label']}, {m['_src']}) |")

    out = HERE / "challenge_v3.jsonl"
    if under or exact or over:
        print("\n".join(rep))
        raise SystemExit("challenge_v3 has problems; see above (nothing written)")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    rep.append(f"\nSHA-256 of `challenge_v3.jsonl`: `{hashlib.sha256(out.read_bytes()).hexdigest()}`")
    (HERE / "CHALLENGE_V3_REPORT.md").write_text("\n".join(rep) + "\n", encoding="utf-8")
    print("\n".join(rep))


if __name__ == "__main__":
    main()
