"""Convert challenge_v2_source.tsv to challenge_v2.jsonl and check it against every existing row.

challenge_v2 was written BEFORE any v2 training data and is frozen: never train or tune on it.
Checks: categories, minimal pairs (one YELLOW + one RED each), temperature thresholds, exact and
near-duplicate (MiniLM cosine > 0.92) overlap with every row of train/val/test and challenge.jsonl.
Writes challenge_v2.jsonl and CHALLENGE_V2_REPORT.md (with the SHA-256 of the jsonl).

  cd backend/triage/data && HF_HUB_OFFLINE=1 ../../.venv/Scripts/python build_challenge_v2.py
"""
from __future__ import annotations

import hashlib
import json
import random
from collections import Counter, defaultdict
from pathlib import Path

from build_dataset import (EMBED_MODEL, NEAR_DUP, RANK, SPLITS, embed, norm_text, temp_floor,
                           temperatures_c)

HERE = Path(__file__).resolve().parent
CATEGORIES = ("negation", "wound_minimal_pair", "routine_multi_topic")


def existing_rows() -> list[dict]:
    rows = [dict(json.loads(l), _src=s) for s in SPLITS
            for l in open(HERE / "splits" / f"{s}.jsonl", encoding="utf-8")]
    rows += [dict(json.loads(l), _src="challenge")
             for l in open(HERE / "challenge.jsonl", encoding="utf-8")]
    return rows


def main() -> None:
    rows = []
    for ln, line in enumerate((HERE / "challenge_v2_source.tsv").read_text(encoding="utf-8").splitlines(), 1):
        if not line.strip() or line.startswith("#"):
            continue
        cat, label, pair, surgery, text = line.split("\t")
        assert cat in CATEGORIES, (ln, cat)
        assert label in RANK, (ln, label)
        if surgery == "ANY":
            surgery = random.Random("surgery:" + text).choice(["TKA", "THA"])
        r = {"id": f"CH2-{len(rows) + 1:03d}", "text": text, "label": label, "category": cat,
             "surgery": surgery, "origin": "challenge_v2", "generator": "claude-opus-5-5",
             "written_before_v2_training": True}
        if pair != "-":
            r["pair"] = pair
        rows.append(r)

    pairs = defaultdict(list)
    for r in rows:
        if r["category"] == "wound_minimal_pair":
            pairs[r["pair"]].append(r["label"])
    assert all(sorted(v) == ["RED", "YELLOW"] for v in pairs.values()), pairs
    assert len({norm_text(r["text"]) for r in rows}) == len(rows), "duplicate inside challenge_v2"

    old = existing_rows()
    old_norm = {norm_text(r["text"]): r for r in old}
    exact = [r for r in rows if norm_text(r["text"]) in old_norm]
    e_new = embed([r["text"] for r in rows])
    e_old = embed([r["text"] for r in old])
    sims = e_new @ e_old.T
    best = sims.argmax(1)
    within = e_new @ e_new.T
    for i in range(len(rows)):
        within[i, i] = 0

    rep = ["# Challenge set v2 report\n",
           "Generated by `build_challenge_v2.py`. `challenge_v2.jsonl` was written on 2026-11-12 "
           "**before** any v2 training data (`authored_v2/`) existed, labelled by "
           "`LABELLING_GUIDELINE.md` v1.1, and committed on its own. It must never be used for "
           "training or tuning; the v2 training rows were near-duplicate-checked against it.\n",
           f"Rows: **{len(rows)}**. Minimal pairs: {len(pairs)} (each one YELLOW + one RED).\n",
           "| category | rows | RED | YELLOW | GREEN |", "|---|---:|---:|---:|---:|"]
    for c in CATEGORIES:
        cc = Counter(r["label"] for r in rows if r["category"] == c)
        rep.append(f"| {c} | {sum(cc.values())} | {cc['RED']} | {cc['YELLOW']} | {cc['GREEN']} |")
    tot = Counter(r["label"] for r in rows)
    rep.append(f"| **all** | **{len(rows)}** | **{tot['RED']}** | **{tot['YELLOW']}** | **{tot['GREEN']}** |\n")

    under = [(r, temperatures_c(r["text"])) for r in rows
             if RANK[r["label"]] < RANK[temp_floor(temperatures_c(r["text"]))]]
    rep.append(f"Rows labelled below the temperature in their text: {len(under)}.")
    for r, cs in under:
        rep.append(f"- `{r['id']}` {r['label']} {cs}: {r['text']}")
    rep.append(f"\nExact (normalised) matches with train/val/test/challenge: **{len(exact)}**.")
    over = [(i, float(sims[i, best[i]])) for i in range(len(rows)) if sims[i, best[i]] > NEAR_DUP]
    rep.append(f"\nNear-duplicates of an existing row ({EMBED_MODEL}, cosine > {NEAR_DUP}): "
               f"**{len(over)}**. Highest similarity to any existing row: **{float(sims.max()):.3f}**; "
               f"median of each row's closest match: {float(sorted(sims.max(1))[len(rows) // 2]):.3f}. "
               f"Highest similarity between two challenge_v2 rows (minimal pairs are meant to be "
               f"close): {float(within.max()):.3f}.")
    for i, s in over:
        m = old[best[i]]
        rep.append(f"- {s:.3f} `{rows[i]['id']}` \"{rows[i]['text']}\" ~ `{m['id']}` ({m['_src']}) \"{m['text']}\"")
    rep.append("\nClosest existing row for the 10 most similar challenge_v2 rows:\n")
    rep.append("| cosine | challenge_v2 | closest existing row |")
    rep.append("|---:|---|---|")
    for i in sorted(range(len(rows)), key=lambda i: -sims[i, best[i]])[:10]:
        m = old[best[i]]
        rep.append(f"| {sims[i, best[i]]:.3f} | {rows[i]['text']} ({rows[i]['label']}) | "
                   f"{m['text']} ({m['label']}, {m['_src']}) |")

    out = HERE / "challenge_v2.jsonl"
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    rep.append(f"\nSHA-256 of `challenge_v2.jsonl`: `{hashlib.sha256(out.read_bytes()).hexdigest()}`")
    (HERE / "CHALLENGE_V2_REPORT.md").write_text("\n".join(rep) + "\n", encoding="utf-8")
    print("\n".join(rep))
    if under or exact or over:
        raise SystemExit("challenge_v2 has problems; see report")


if __name__ == "__main__":
    main()
