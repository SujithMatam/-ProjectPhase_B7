"""
Builds eval/agents/REPORT.md from the four result files written by
run_conversations.py:

    results/baseline_b8f0cc5.json               direct calls, baseline commit
    results/head.json                           direct calls, this branch
    results/baseline_b8f0cc5_orchestrator.json  via LAMOrchestrator.process
    results/head_orchestrator.json              via LAMOrchestrator.process

    .venv/Scripts/python.exe eval/agents/build_report.py
"""

from __future__ import annotations

import json
import shutil
from datetime import date
from collections import Counter, defaultdict
from pathlib import Path
from typing import Any, Dict, List

HERE = Path(__file__).resolve().parent
RESULTS = HERE / "results"
REPORTS_DIR = HERE.parents[1] / "eval" / "reports"
AGENTS = ("pain", "recovery", "rehab")
AGENT_NAME = {"pain": "Pain & Symptoms", "recovery": "Recovery Progress", "rehab": "Rehabilitation"}


def load(label: str) -> Dict[str, Any]:
    return json.loads((RESULTS / f"{label}.json").read_text(encoding="utf-8"))


def per_agent(data: Dict[str, Any]) -> Dict[str, Counter]:
    out: Dict[str, Counter] = defaultdict(Counter)
    for run in data["runs"]:
        s, a = run["summary"], out[run["agent"]]
        a["conversations"] += 1
        a["passed"] += s["properties_passed"]
        a["total"] += s["properties_total"]
        a["clean"] += int(s["properties_passed"] == s["properties_total"])
        a["questions"] += s["questions"]
        a["fields"] += s["fields_total"]
        a["reused"] += s["record_fields_reused"]
        a["offered"] += s["record_fields_offered"]
        a["rows"] += s["rows_persisted"]
        a["misrouted"] += len(s.get("misrouted_turns", []))
        a["continuation"] += len(s.get("misrouted_continuation", []))
        a["fresh"] += len(s.get("misrouted_fresh", []))
        a["red"] += len(s.get("red_preempted_turns", []))
        a["turns"] += len(run["turns"])
    return out


def per_property(data: Dict[str, Any]) -> Dict[str, Counter]:
    out: Dict[str, Counter] = defaultdict(Counter)
    for run in data["runs"]:
        for p in run["properties"]:
            out[p["name"]]["total"] += 1
            out[p["name"]]["passed"] += int(p["passed"])
    return out


def pct(passed: int, total: int) -> str:
    return f"{passed}/{total} ({100 * passed / total:.0f}%)" if total else "-"


def fields_cell(summary: Dict[str, Any]) -> str:
    return f"{' · '.join(str(n) for n in summary['fields_per_turn'])} (={summary['fields_total']})"


def failures(data: Dict[str, Any]) -> List[str]:
    lines = []
    for run in data["runs"]:
        for p in run["properties"]:
            if not p["passed"]:
                where = f" turn {p['turn']}" if p["turn"] else ""
                lines.append(f"- `{run['id']}`{where} -- **{p['name']}**: {p['detail']}")
    return lines


def misroute_lines(data: Dict[str, Any]) -> List[str]:
    lines = []
    for run in data["runs"]:
        for t in run["turns"]:
            if t.get("misroute_kind"):
                kind = {"continuation": "answer to a pending question", "fresh_classification": "fresh classification",
                        "red_preempted": "RED pre-empted (cumulative Pain triage)"}[t["misroute_kind"]]
                pending = f", pending `{t['pending_before']}`" if t.get("pending_before") else ""
                lines.append(f"| `{run['id']}` | {t['index']} | \"{t['patient']}\" | {t['routed_to']} | {kind}{pending} |")
    return lines


def main() -> int:
    before, after = load("baseline_b8f0cc5"), load("head")
    before_o, after_o = load("baseline_b8f0cc5_orchestrator"), load("head_orchestrator")
    ba, aa = per_agent(before), per_agent(after)
    bao, aao = per_agent(before_o), per_agent(after_o)
    bp, ap = per_property(before), per_property(after)
    total = lambda agg, key: sum(agg[a][key] for a in AGENTS)

    L: List[str] = []
    w = L.append
    w("# Pain, Recovery and Rehab agents -- conversation-level evaluation")
    w("")
    w(f"24 scripted conversations (8 per agent) run turn by turn through the real agent classes, "
      f"once against the baseline commit `{before['meta']['commit']}` (in a git worktree) and once against "
      f"this branch (`{after['meta']['commit']}`), with the same seeded records, the same patient turns and the "
      f"same checks. Generated by `eval/agents/build_report.py` from `eval/agents/results/*.json`; full "
      f"per-property results and transcripts for each run are in `eval/agents/results/*.md`.")
    w("")
    w("## Headline")
    w("")
    w("| Run | Properties passed | Conversations with every property passing |")
    w("|---|---|---|")
    w(f"| Baseline `{before['meta']['commit']}`, direct calls | {pct(total(ba, 'passed'), total(ba, 'total'))} | {total(ba, 'clean')}/24 |")
    w(f"| This branch `{after['meta']['commit']}`, direct calls | {pct(total(aa, 'passed'), total(aa, 'total'))} | {total(aa, 'clean')}/24 |")
    w(f"| Baseline, via `LAMOrchestrator.process` | {pct(total(bao, 'passed'), total(bao, 'total'))} | {total(bao, 'clean')}/24 |")
    w(f"| This branch, via `LAMOrchestrator.process` | {pct(total(aao, 'passed'), total(aao, 'total'))} | {total(aao, 'clean')}/24 |")
    w("")
    w(f"Through the orchestrator, **{total(aao, 'misrouted')} of {total(aao, 'turns')} turns on this branch are misrouted** "
      f"({total(aao, 'continuation')} are answers to a question the agent had just asked -- the continuation-hook gap -- "
      f"and {total(aao, 'fresh')} are fresh-classification misses), plus {total(aao, 'red')} turn pre-empted by the "
      f"cumulative RED safety path (correct behaviour, counted separately). Baseline: {total(bao, 'misrouted')} misrouted "
      f"({total(bao, 'continuation')} pending-answer, {total(bao, 'fresh')} fresh), {total(bao, 'red')} RED pre-empted. "
      f"The baseline's pending-answer count is low only because its Rehabilitation agent never asks anything, so "
      f"no answer of its can be 'pending'.")
    w("")

    w("## Before / after per agent (direct calls, LLM stubbed)")
    w("")
    w("| Agent | Properties passed (before -> after) | Clean conversations | Questions asked | Fields collected | Record fields reused | Rows persisted |")
    w("|---|---|---|---|---|---|---|")
    for agent in AGENTS:
        b, a = ba[agent], aa[agent]
        w(f"| {AGENT_NAME[agent]} | {pct(b['passed'], b['total'])} -> **{pct(a['passed'], a['total'])}** | "
          f"{b['clean']}/8 -> {a['clean']}/8 | {b['questions']} -> {a['questions']} | {b['fields']} -> {a['fields']} | "
          f"{b['reused']}/{b['offered']} -> {a['reused']}/{a['offered']} | {b['rows']} -> {a['rows']} |")
    w(f"| **All** | {pct(total(ba, 'passed'), total(ba, 'total'))} -> **{pct(total(aa, 'passed'), total(aa, 'total'))}** | "
      f"{total(ba, 'clean')}/24 -> {total(aa, 'clean')}/24 | {total(ba, 'questions')} -> {total(aa, 'questions')} | "
      f"{total(ba, 'fields')} -> {total(aa, 'fields')} | {total(ba, 'reused')}/{total(ba, 'offered')} -> "
      f"{total(aa, 'reused')}/{total(aa, 'offered')} | {total(ba, 'rows')} -> {total(aa, 'rows')} |")
    w("")
    w("*Questions asked* is the number of agent turns that ended with a tracked question; *fields collected* the "
      "distinct fields the agent held at some point in each conversation (read from its own state, never from the "
      "reply text); *record fields reused* the seeded record items the agent visibly used (confirmed, referenced or "
      "fed back); *rows persisted* new `symptom_assessments` rows plus inserted or updated `metrics` rows. A similar "
      "question count before and after does not mean the same behaviour: the baseline Recovery agent spends its "
      "questions re-asking flexion, and the baseline Rehabilitation agent asks nothing at all.")
    w("")

    w("## Per conversation (direct calls)")
    w("")
    w("| Conversation | Properties before -> after | Questions | Fields collected per turn, before | after | Record fields reused | Rows persisted |")
    w("|---|---|---|---|---|---|---|")
    b_runs = {r["id"]: r for r in before["runs"]}
    for run in after["runs"]:
        b, a = b_runs[run["id"]]["summary"], run["summary"]
        w(f"| `{run['id']}` | {b['properties_passed']}/{b['properties_total']} -> {a['properties_passed']}/{a['properties_total']} | "
          f"{b['questions']} -> {a['questions']} | {fields_cell(b)} | {fields_cell(a)} | "
          f"{b['record_fields_reused']}/{b['record_fields_offered']} -> {a['record_fields_reused']}/{a['record_fields_offered']} | "
          f"{b['rows_persisted']} -> {a['rows_persisted']} |")
    w("")
    w("Conversations c01-c06 are the six transcripts from the `*_CHANGES.md` files (Pain TKA calf, Pain THA groin, "
      "Recovery TKA day 10, Recovery THA day 30, Rehab TKA stairs, Rehab THA missed days); c07 is the Rehab "
      "safety-hold transcript. The three Pain bug cases are c08 (non-numeric score reply), c09 (an off-topic "
      "question stored as the onset) and c10 (restart after a detour). THA cases: c02, c04, c06.")
    w("")

    w("## Per property (direct calls, all agents)")
    w("")
    w("| Property | Before | After |")
    w("|---|---|---|")
    for name in sorted(set(bp) | set(ap)):
        w(f"| `{name}` | {pct(bp[name]['passed'], bp[name]['total'])} | {pct(ap[name]['passed'], ap[name]['total'])} |")
    w("")

    w("In direct mode `triage_equals_engine` checks that each agent copies the upstream level it is given, and both "
      "versions do. `no_passage_id_in_text` passes on the baseline only because it never reached an assessment "
      "that could name one.")
    w("")
    w("## Via the orchestrator: misrouted turns")
    w("")
    w("Every turn goes through `LAMOrchestrator.process()` (classifier, continuation hooks, triage, router). A turn is "
      "*misrouted* when it reaches a different agent than the conversation's own; the agent then never sees it and "
      "the per-turn properties that depend on it fail too, so this mode measures the gap instead of hiding it.")
    w("")
    w("| Agent | Turns | Misrouted, before | Misrouted, after | of which answers to a pending question (after) | RED pre-empted (after) | Properties before -> after |")
    w("|---|---|---|---|---|---|---|")
    for agent in AGENTS:
        b, a = bao[agent], aao[agent]
        w(f"| {AGENT_NAME[agent]} | {a['turns']} | {b['misrouted']} | **{a['misrouted']}** | {a['continuation']} | {a['red']} | "
          f"{pct(b['passed'], b['total'])} -> {pct(a['passed'], a['total'])} |")
    w(f"| **All** | {total(aao, 'turns')} | {total(bao, 'misrouted')} | **{total(aao, 'misrouted')}** | "
      f"{total(aao, 'continuation')} | {total(aao, 'red')} | {pct(total(bao, 'passed'), total(bao, 'total'))} -> "
      f"{pct(total(aao, 'passed'), total(aao, 'total'))} |")
    w("")
    w("Misrouted and pre-empted turns on this branch:")
    w("")
    w("| Conversation | Turn | Patient said | Went to | Kind |")
    w("|---|---|---|---|---|")
    L.extend(misroute_lines(after_o))
    w("")
    w("What the list shows:")
    w("")
    w("- **Rehabilitation has no continuation hook.** Every answer to its safety, done-today or barrier question "
      "is re-classified from scratch: a bare \"no\" / \"not yet\" goes to Recovery (low-confidence fallback) and "
      "\"no, nothing hurts\" / \"too sore\" goes to Pain. Through `/api/chat` the two-question flow never completes "
      "(Rehab shared change 1).")
    w("- **Recovery's hook misses some answer shapes**: \"I use a walker\" goes to Rehabilitation and \"one step at a "
      "time\" to Daily Activity while a Recovery question is pending (Recovery shared changes 2 and 5). `current_rom` "
      "is not forwarded by the router either, so c15 asks for flexion and extension the request already carried "
      "(Recovery shared change 1).")
    w("- **Fresh classification of opening turns**: \"It's about a 5 out of 10, it came on gradually, and it's "
      "behind the knee.\", \"My knee aches a little, I took my painkillers an hour ago.\" and \"Am I on track with "
      "my knee?\" go to IntakeContextAgent, and \"Can I go up and down the stairs yet?\" to Daily Activity; the "
      "conversation never reaches the agent, so its later answers are classified fresh too (c11, c13). This is "
      "the intent classifier, outside this branch, and new information from this eval.")
    w("- **c01 turn 4 is RED by design**: the orchestrator's cumulative Pain triage combines 7/10, sudden onset "
      "and calf into a RED result, and the safety path answers. The `triage_equals_engine` property accepts this "
      "(the engine's own, more severe decision) and lists it in the detail.")
    w("")

    w("## Remaining failures on this branch (direct calls)")
    w("")
    L.extend(failures(after) or ["- none"])
    w("")
    w("- c18: past day 84 the Recovery close has no next milestone. It ends with \"Longer term, the guidance "
      "describes ...\" and the 'recovery check' offer, with no explicit next step. Left failing on purpose: it is "
      "a real gap in the close, not a scripting problem.")
    w("")
    w("Two Recovery defects showed up in the orchestrator run of c14, where routing shifted the answers by one "
      "turn. Both reproduce with direct calls on this branch:")
    w("")
    w("- **A unit-less match on the pending field**: with flexion pending, \"about 5 minutes\" is stored as "
      "*flexion of 5°* and compared with the day-7 range. The loose-number rule for the pending numeric field "
      "does not reject a number with a different unit.")
    w("- **A volunteered value in the opening message is ignored**: \"about 60 degrees\" as the first message gets "
      "\"About how many degrees can you currently bend your knee?\", so the patient has to repeat it.")
    w("")
    w("Other observation from building the scripts: `pain_logic.mentions_medication()` knows generic words "
      "(\"medication\", \"painkillers\") but not drug names. \"I took paracetamol an hour ago\" never triggers the "
      "medication-effect question, in either version. c13 says \"painkillers\" so that it tests the branch.")
    w("")

    w("## What is checked")
    w("")
    w("Each conversation (`eval/agents/conversations/*.json`) seeds a patient record in a fresh temp database "
      "(procedure, surgery date, `metrics` rows, prior `symptom_assessments`, weight-bearing status), then plays "
      "the patient's turns. Properties:")
    w("")
    w("| Property | Meaning |")
    w("|---|---|")
    w("| `collects_field` | after this turn the agent's own state holds the field (Pain: the assessment it builds; Recovery/Rehab: the session facts) |")
    w("| `does_not_collect`, `does_not_store_unfitting_reply` | an unfitting reply is not stored (e.g. onset must not contain \"shower\") |")
    w("| `no_question_for_record_data` | no question asks from scratch for a field the record already holds; confirming the recorded value is fine, and so is asking after the patient did not confirm it |")
    w("| `no_reask_of_collected_field` | no question re-asks a field collected earlier in the conversation |")
    w("| `max_questions` | total agent questions is at most the scripted maximum |")
    w("| `final_turn_closes_interview` | the last turn asks nothing |")
    w("| `final_has_trend_or_checkpoint` | Pain: \"Compared with last time\"; Recovery: a named checkpoint day or the long-term guidance; Rehab: guidance anchored to the post-op day. Not required for the safety hold (c07), which gives no guidance by design |")
    w("| `final_has_next_step` | Pain \"Next step:\", Recovery \"Next milestone:\", Rehab \"Next session:\" |")
    w("| `triage_equals_engine` | every reply's triage level equals `SafetyTriageEngine.evaluate()` on the same turn text |")
    w("| `no_passage_id_in_text` | no `TKA-03` / `EV-THA-REC-02`-style id in any reply |")
    w("| `abandoned_persists_nothing` | an interview the patient leaves writes no rows |")
    w("| `persists_on_completion` | a completed interview writes at least the scripted number of rows |")
    w("| `weight_bearing_record_unchanged` | `surgeries.weight_bearing_status` is never written |")
    w("| `reply_matches`, `reply_does_not_match` | per-turn wording checks (\"None pain\", \"pause heel slides\", knee-only advice for a hip, loading advice under NWB) |")
    w("| `routed_to_expected_agent` | orchestrator mode only: no turn misrouted (RED pre-emption excluded) |")
    w("")

    w("## How it was run")
    w("")
    w("```")
    w("cd backend")
    w("git worktree add --detach <tmp>/baseline_b8f0cc5 b8f0cc5")
    w(".venv/Scripts/python.exe eval/agents/run_conversations.py --label head")
    w(".venv/Scripts/python.exe eval/agents/run_conversations.py --label baseline_b8f0cc5 --backend-dir <tmp>/baseline_b8f0cc5/backend")
    w(".venv/Scripts/python.exe eval/agents/run_conversations.py --via-orchestrator --label head_orchestrator")
    w(".venv/Scripts/python.exe eval/agents/run_conversations.py --via-orchestrator --label baseline_b8f0cc5_orchestrator --backend-dir <tmp>/baseline_b8f0cc5/backend")
    w(".venv/Scripts/python.exe eval/agents/build_report.py")
    w("```")
    w("")
    w("- Direct calls to `PainSymptomsAgent` / `RecoveryProgressAgent` / `RehabilitationAgent.handle()`, as the tests "
      "make them, with `precomputed_triage` from `SafetyTriageEngine` on the turn's text. Arguments an older "
      "`handle()` does not accept are dropped, so the same script runs on the baseline.")
    w("- `PATIENT_DATABASE_PATH` points at a fresh temp sqlite file per run; every `*SMTP*` / `*DOCTOR_ALERT*` "
      "variable is removed and the RED doctor-alert hook is a no-op.")
    w("- The LLM is stubbed by default, the same way as for the `*_CHANGES.md` transcripts: Pain and Recovery get an "
      "empty `ChatAgent` reply (so the deterministic close is measured), and Rehab gets the local LLM offline "
      "(`_query_llama` returns None, so ChatAgent's real retrieval and fallback run). `--live` uses Ollama "
      "instead. The numbers above are from stubbed runs; no live run is included.")
    w("- The c10 detour turn (\"Can I climb stairs?\") is played with a scripted Daily Activity reply in direct "
      "mode. Through the orchestrator it is really routed, and Daily Activity is the expected agent.")
    w("")

    w("## Shared changes needed (combined, outside this branch's scope)")
    w("")
    w("Merged from the three `*_CHANGES.md` files; *measured here* marks items this eval puts a number on.")
    w("")
    w(f"1. **`lam/orchestrator.py` -- Rehabilitation continuation hook** (Rehab 1). *Measured here:* "
      f"{aao['rehab']['continuation']} Rehab answers to a pending question misrouted, {aao['rehab']['misrouted']} Rehab turns misrouted in all.")
    w(f"2. **`lam/orchestrator.py` -- Recovery continuation coverage and precedence** (Recovery 2, 5): answer shapes "
      f"such as \"I use a walker\" / \"one step at a time\", and Pain's hook running first for a bare \"yes\". "
      f"*Measured here:* {aao['recovery']['continuation']} Recovery answers misrouted.")
    w("3. **`lam/orchestrator.py` -- cumulative safety after a detour** (Pain 2): pass `user_message` to "
      "`is_active_assessment_continuation()` so the resumed turn's accumulated facts are triaged too.")
    w("4. **`agents/agent_router.py` -- forward `current_rom` to the Recovery agent** (Recovery 1). *Measured here:* "
      "c15 reuses 2/2 request values in direct calls, 0/2 through the orchestrator.")
    w("5. **Intent classifier** (Pain 5, Recovery 5, Rehab 5): keep \"pain\" / \"recovery\" / \"rehab\" so the "
      "check-in offers route back; \"safe\" sends exercise questions to Medication first. *Measured here:* "
      f"{total(aao, 'fresh')} fresh-classification misses on this branch, among them opening turns sent to "
      "IntakeContextAgent (c11, c13, c14) and \"Can I go up and down the stairs yet?\" sent to Daily Activity (c05).")
    w("6. **`agents/chat_agent.py` -- token budget** (Pain 1, Recovery 3, Rehab 3): "
      "`answer_question(..., max_tokens=None)` passed through to `num_predict`.")
    w("7. **`agents/chat_agent.py` -- generic exercise fallback** (Rehab 2): the knee-only exercise text and "
      "\"Swelling ... is normal\" line still reach other callers.")
    w("8. **`patient_database.py` -- `upsert_daily_metrics()`** (Pain 3, Recovery 4, Rehab 4): three agents now "
      "write `metrics` through `patient_memory.write_today_metrics()` with their own SQL; `metrics.swelling` now "
      "holds patient wording next to the seeded descriptors.")
    w("9. **`symptom_assessments.medication_effect` column** (Pain 4): still collected, still not persisted.")
    w("10. **`surgeries.weight_bearing_status` as a controlled value** (Rehab 6): the four codes instead of free text.")
    w("11. **Flutter client / `ChatRequest`** (Recovery 6, Rehab 7): rely on `surgery_date` for the post-op day "
      "(mismatches are now logged), and stop re-sending `exercise_history` / `current_rom` the backend already logs.")
    w("12. **Timezone** (Recovery 7): the server's local date is \"today\" for the post-op day and `metrics.date`; "
      "accepted limitation.")
    w("13. **`AGENTS_BASELINE.md` headline count** (Pain 6): should read 65 passed, 1 failed, 66 tests.")
    w("")

    text = "\n".join(L) + "\n"
    (HERE / "REPORT.md").write_text(text, encoding="utf-8")
    REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(HERE / "REPORT.md", REPORTS_DIR / f"{date.today().isoformat()}_agents-conversations-report.md")
    print(f"wrote {HERE / 'REPORT.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
