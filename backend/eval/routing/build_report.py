"""
Builds eval/routing/REPORT.md from the result files written by
run_routing_benchmark.py:

    results/baseline_b6c1730.json       classifier as it was on the branch
    results/fix_a_requested.json        the three requested changes
    results/fix_b_intake_gate.json      + the semantic intake-cue gate (shipped)
    results/semantic_first.json         the step-4 experiment (flag on)

    .venv/Scripts/python.exe eval/routing/build_report.py
"""

from __future__ import annotations

import json
import shutil
from collections import Counter, defaultdict
from datetime import date
from pathlib import Path
from typing import Any, Dict, List, Optional

HERE = Path(__file__).resolve().parent
RESULTS = HERE / "results"
REPORTS_DIR = HERE.parents[1] / "eval" / "reports"

AGENTS = (
    "pain_symptoms", "recovery_progress", "rehabilitation", "wound_care", "medication",
    "daily_activity", "nutrition", "mental_wellbeing", "intake_context",
)
NAME = {
    "pain_symptoms": "Pain & Symptoms", "recovery_progress": "Recovery Progress",
    "rehabilitation": "Rehabilitation", "wound_care": "Wound Care", "medication": "Medication",
    "daily_activity": "Daily Activity", "nutrition": "Nutrition",
    "mental_wellbeing": "Mental Wellbeing", "intake_context": "Intake / Context",
}

BASELINE = "baseline_b6c1730"
STEPS = [
    ("fix_a_requested", "A: the three requested changes"),
    ("fix_b_intake_gate", "B: A + semantic intake-cue gate (shipped)"),
]
EXPERIMENT = "semantic_first"


def load(label: str) -> Optional[Dict[str, Any]]:
    path = RESULTS / f"{label}.json"
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def pct(acc: Dict[str, int]) -> str:
    return f"{acc['correct']}/{acc['n']} ({100 * acc['correct'] / acc['n']:.0f}%)" if acc["n"] else "-"


def delta(a: Dict[str, int], b: Dict[str, int]) -> str:
    d = b["correct"] - a["correct"]
    return f"{'+' if d > 0 else ''}{d}" if d else "="


def rows_by_id(data: Dict[str, Any]) -> Dict[str, Dict[str, Any]]:
    return {r["id"]: r for r in data["rows"]}


def group_of(rule: Optional[str]) -> str:
    if not rule:
        return "-"
    for prefix in ("keyword order", "overbroad keyword", "intake rule", "semantic prototype pull",
                   "semantic threshold", "patient-record", "medication follow-up"):
        if rule.startswith(prefix):
            return prefix
    return rule.split(":")[0]


def main() -> int:
    base = load(BASELINE)
    steps = [(label, title, load(label)) for label, title in STEPS]
    steps = [(l, t, d) for l, t, d in steps if d is not None]
    final_label, final_title, final = steps[-1]
    exp = load(EXPERIMENT)
    runs = [(BASELINE, "Baseline", base)] + [(l, t, d) for l, t, d in steps]
    if exp is not None:
        runs.append((EXPERIMENT, "Experiment: semantic-first (flag on, not shipped)", exp))

    cases = base["rows"]
    n_cases = len(cases)
    n_clear = sum(1 for r in cases if r["confidence"] == "clear")
    n_deb = n_cases - n_clear
    n_answers = sum(1 for r in cases if r["kind"] == "answer")
    sources = Counter(r["source"].split(":")[0] for r in cases)
    base_rows, final_rows = rows_by_id(base), rows_by_id(final)

    L: List[str] = []
    w = L.append
    w("# Intent routing benchmark -- before / after per agent")
    w("")
    w(f"{n_cases} labelled single patient messages (`eval/routing/cases.py`), each scored on "
      f"`IntentClassifier.classify_detailed()` and, separately, on the orchestrator's final routing "
      f"(`LAMOrchestrator.process()` for a brand-new patient, `AgentRouter.dispatch` stubbed). "
      f"{n_clear} cases are *clear*, {n_deb} *debatable* (two or three acceptable agents); "
      f"{n_answers} are answers to a pending question, which carry no routable signal on their own. "
      f"Sources: {sources['phase2']} from `test_phase2_intent.py`, {sources['orchestration']} from "
      f"`test_multi_agent_orchestration.py`, {sources['recovery_test']} from `test_recovery_progress_agent.py`, "
      f"{sources['report']} misroutes from `eval/agents/REPORT.md`, {sources['audit']} audit sentences, "
      f"{sources['new']} new patient-language openings (20 per agent, Indian-English phrasing and spelling slips) and "
      f"{sources['intake_guard']} intake guards. Generated by `eval/routing/build_report.py` from "
      f"`eval/routing/results/*.json`; every case, score and decision path is in `eval/routing/results/<label>.md`.")
    w("")
    w("A prediction is correct when it is in the case's acceptable set. Two cases that the orchestrator must "
      "pre-empt (emergency, out of scope) are excluded from the per-agent tables and reported separately. "
      "Orchestrator *lenient* counts a turn as routed correctly when at least one dispatched agent is acceptable "
      "(the `eval/agents` definition); *strict* requires every dispatched agent to be acceptable.")
    w("")

    # ---------------------------------------------------------------- headline
    w("## Headline")
    w("")
    w("| Run | Classifier | Classifier, clear only | Classifier, openings only | Orchestrator (lenient) | Orchestrator (strict) |")
    w("|---|---|---|---|---|---|")
    for label, title, d in runs:
        o = d["summary"]["overall"]
        w(f"| {title} (`{label}`) | **{pct(o['classifier'])}** | {pct(o['classifier_clear'])} | "
          f"{pct(o['classifier_openings'])} | **{pct(o['orchestrator'])}** | {pct(o['orchestrator_strict'])} |")
    w("")
    bo, fo = base["summary"]["overall"], final["summary"]["overall"]
    w(f"The shipped change (step B) moves the classifier from {pct(bo['classifier'])} to {pct(fo['classifier'])} and "
      f"the orchestrator's routing from {pct(bo['orchestrator'])} to {pct(fo['orchestrator'])}, with no agent below "
      f"its baseline at either step (table below). On the conversation eval (`eval/agents/REPORT.md`, re-run after "
      f"the fix) the orchestrator misroutes 10 of 97 turns instead of 11: c14's opening \"Am I on track with my "
      f"knee?\" now reaches Recovery.")
    w("")

    # ---------------------------------------------------------------- per agent
    w("## Per agent, before / after")
    w("")
    head = "| Agent | n |"
    sep = "|---|---|"
    for _, title, _ in runs:
        head += f" {title.split(':')[0].split(' (')[0]} classifier | orchestrator |"
        sep += "---|---|"
    w(head)
    w(sep)
    for agent in AGENTS:
        if agent not in base["summary"]["per_agent"]:
            continue
        line = f"| {NAME[agent]} | {base['summary']['per_agent'][agent]['classifier']['n']} |"
        prev = None
        for label, _, d in runs:
            e = d["summary"]["per_agent"][agent]
            c, o = e["classifier"], e["orchestrator"]
            if prev is None:
                line += f" {pct(c)} | {pct(o)} |"
            else:
                line += f" {pct(c)} ({delta(prev[0], c)}) | {pct(o)} ({delta(prev[1], o)}) |"
            prev = (c, o)
        w(line)
    line = f"| **All** | {bo['classifier']['n']} |"
    prev = None
    for label, _, d in runs:
        o = d["summary"]["overall"]
        c, oo = o["classifier"], o["orchestrator"]
        if prev is None:
            line += f" **{pct(c)}** | **{pct(oo)}** |"
        else:
            line += f" **{pct(c)}** ({delta(prev[0], c)}) | **{pct(oo)}** ({delta(prev[1], oo)}) |"
        prev = (c, oo)
    w(line)
    w("")
    w("The bracketed delta is against the previous column. Acceptance rule for a step: no agent's classifier "
      "accuracy may drop against the baseline.")
    w("")
    w("| Step | Agents below baseline (classifier) | Agents below baseline (orchestrator, lenient) | Accepted |")
    w("|---|---|---|---|")
    for label, title, d in steps + ([(EXPERIMENT, "Experiment: semantic-first", exp)] if exp else []):
        drops_c = [NAME[a] for a in AGENTS if a in d["summary"]["per_agent"] and
                   d["summary"]["per_agent"][a]["classifier"]["correct"] < base["summary"]["per_agent"][a]["classifier"]["correct"]]
        drops_o = [NAME[a] for a in AGENTS if a in d["summary"]["per_agent"] and
                   d["summary"]["per_agent"][a]["orchestrator"]["correct"] < base["summary"]["per_agent"][a]["orchestrator"]["correct"]]
        accepted = "yes" if not drops_c and label != EXPERIMENT else ("not shipped (experiment)" if label == EXPERIMENT else "no")
        w(f"| {title} | {', '.join(drops_c) or 'none'} | {', '.join(drops_o) or 'none'} | {accepted} |")
    w("")

    # ---------------------------------------------------------------- diagnosis
    w("## Diagnosis of the baseline misses, by rule")
    w("")
    base_misses = [r for r in cases if not r.get("orchestrator_expected") and not r["classifier_correct"]]
    groups: Dict[str, List[Dict[str, Any]]] = defaultdict(list)
    for r in base_misses:
        groups[group_of(r["classifier_rule"])].append(r)
    w(f"{len(base_misses)} classifier misses on the baseline. Each is attributed to the rule that produced it, read "
      "from the classifier's own tables (`keyword_hits`, `intake_signals` and `decision_path` in the result JSON).")
    w("")
    w("| Group | Misses | Rule | What fixed it |")
    w("|---|---|---|---|")
    explain = {
        "intake rule": ("`_INTRODUCTION_PATTERNS` treated any `I am <word>` / `I'm <word>` as an introduction, so a "
                        "statement without a question mark or a listed symptom word became INTAKE_CONTEXT in the "
                        "deterministic step (\"I am feeling okay today\", \"I'm walking with a walker now\", "
                        "\"Recovery check please, I am on day 21 now\").",
                        "Step A: `I am` / `I'm` no longer count on their own; the message must also carry an intake "
                        "cue (greeting, \"my name is\", an intake phrase such as \"I had ... surgery/replacement\", "
                        "or a capitalised name right after \"I am\" in the original message)."),
        "keyword order": ("Medication is the first keyword rule, and its list held the generic words \"safe\", "
                          "\"safety\", \"schedule\", \"timing\", \"warning\"; Daily Activity's \"stand\" / \"sitting\" "
                          "and Rehab's \"physio\" are also checked before Recovery and Mental Wellbeing.",
                          "Step A removed the five generic words from the medication list (a message that pairs them "
                          "with a drug word still matches through the drug word). The order itself was not changed; "
                          "the remaining three keyword-order misses (\"stand\" in \"where I stand\", \"physio\" before "
                          "\"scared\", \"sitting\" before \"lonely\") are listed below as not fixed."),
        "overbroad keyword": ("A single generic word owns the turn: \"recovery\" (\"feeling down ... during this "
                              "recovery\", \"fruits ... during recovery\"), \"worry\" (\"should I worry?\"), \"pain\" "
                              "in \"pain killer\", \"safe\" in \"is it safe to walk\".",
                              "Only the \"safe\" case is fixed (step A). The others need a decision about what the "
                              "`recovery`, `worry` and `pain killer` words should mean and were left alone."),
        "semantic prototype pull": ("The INTAKE_CONTEXT prototypes contain \"knee\" and \"surgery\" (\"I had a knee "
                                    "replacement yesterday.\", \"I need to tell you about my surgery.\"), so any knee "
                                    "sentence without a keyword hit lands on intake in the semantic step with a clear "
                                    "margin (\"Am I on track with my knee?\" 0.63, \"When will the knee feel like normal "
                                    "again?\" 0.70, \"Which excercises I should do today for my knee?\" 0.59).",
                                    "Step B: the semantic ranking may only pick INTAKE_CONTEXT when the message carries "
                                    "an intake cue (the same cue test as step A); otherwise intake is dropped from the "
                                    "ranking and the next-best intent competes against the usual thresholds."),
        "semantic threshold": ("No keyword hit and a semantic result under the thresholds (top-1 < 0.35 or margin < "
                               "0.04) falls through `_classify_by_keywords` to the default, RECOVERY_PROGRESS. Six of "
                               "these are bare answers to a pending question (\"3\", \"gradually\", \"no, nothing "
                               "sharp\") that nothing can route in isolation; the rest are openings whose wording has "
                               "no keyword (\"sweeping and mopping\", \"tea and coffee\", \"Dal, roti, sabzi\").",
                               "Not fixed: changing the thresholds or the keyword-vs-semantic order was out of scope "
                               "for step 3; see the step-4 experiment."),
    }
    for group in ("intake rule", "keyword order", "overbroad keyword", "semantic prototype pull", "semantic threshold"):
        if group in groups:
            rule, fix = explain.get(group, ("", ""))
            w(f"| {group} | {len(groups[group])} | {rule} | {fix} |")
    for group in sorted(groups):
        if group not in explain:
            w(f"| {group} | {len(groups[group])} | | |")
    w("")
    w("A \"substring match\" group was looked for and is not present on this set: the keyword rules already use "
      "word boundaries. The one substring matcher in `intent_classifier.py` is the medication follow-up check "
      "(`\"no\" in text` also matched \"nothing\", \"know\", \"now\"; `\"ok\"` matched \"took\"; `\"pill\"` "
      "matched \"pillow\"), which only runs with a chat history that mentions a medication, so no single-message "
      "case can reach it. Step A switched it to whole-word matching anyway.")
    w("")
    w("### Every baseline miss and where it went after the fix")
    w("")
    w("| Case | Message | Expected (acceptable) | Baseline | Rule (baseline) | After step B |")
    w("|---|---|---|---|---|---|")
    for group in ("intake rule", "keyword order", "overbroad keyword", "semantic prototype pull", "semantic threshold"):
        for r in groups.get(group, []):
            f = final_rows[r["id"]]
            after = f["classifier"]["intent"] + (" ok" if f["classifier_correct"] else f" **x** ({f['classifier']['decision_path']})")
            tag = f" *{r['kind']}*" if r["kind"] != "opening" else ""
            tag += " *debatable*" if r["confidence"] == "debatable" else ""
            w(f"| {r['id']} | \"{r['text']}\"{tag} | {r['expected']} ({', '.join(r['acceptable'])}) | "
              f"{r['classifier']['intent']} | {r['classifier_rule']} | {after} |")
    w("")

    # ---------------------------------------------------------------- what changed
    w("## What changed in `lam/intent_classifier.py`")
    w("")
    w("Step A (the three requested changes):")
    w("")
    w("1. **Whole-word matching in the medication follow-up check.** `_looks_like_medication_follow_up()` used "
      "`marker in text` for both the current turn and the history; it now uses `\\b...\\b`, with the plural forms "
      "(\"doses\", \"tablets\", \"pills\", \"medicines\", \"antibiotics\", \"painkillers\") added so nothing that "
      "matched legitimately before stops matching. The keyword rules themselves already used word boundaries.")
    w("2. **`I am` / `I'm` is no longer an introduction by itself.** `_is_introduction()` now requires an intake cue: "
      "a greeting (whole message, or leading \"Hi, ...\"), \"my name is\", one of the `_INTAKE_PATTERNS` (with "
      "\"I had ... replacement / arthroplasty / operation\" added next to \"I had ... surgery\"), or a capitalised "
      "word right after \"I am\" / \"I'm\" in the original message that is not a common sentence word (\"I am "
      "Rishi\" yes, \"I am Fine\" no). The symptom / question override is unchanged.")
    w("3. **\"safe\", \"safety\", \"schedule\", \"timing\", \"warning\" removed from `_MEDICATION_KEYWORDS`.** "
      "\"purpose\" and \"precaution\" are of the same kind but no benchmark case touches them, so they were left.")
    w("")
    w("Step B (one more change, same spirit, measured separately):")
    w("")
    w("4. **No semantic INTAKE_CONTEXT without an intake cue.** In `classify_detailed()`, after the semantic scores "
      "are computed and before ranking, intake is dropped from the candidates unless `_has_intake_cue()` holds. "
      "The keyword-vs-semantic order and both thresholds are untouched.")
    w("")
    w("Also tried and reverted: adding the word forms \"paining\", \"pains\", \"aches\" to the pain keywords. It "
      "changed no case on this set (\"My knee is paining alot since morning\" is already recovered by step B: with "
      "intake out of the ranking the Pain prototype wins the margin), so it is not shipped.")
    w("")

    # ---------------------------------------------------------------- remaining misses
    w("## Remaining classifier misses after step B")
    w("")
    final_misses = [r for r in final["rows"] if not r.get("orchestrator_expected") and not r["classifier_correct"]]
    fgroups: Dict[str, List[Dict[str, Any]]] = defaultdict(list)
    for r in final_misses:
        fgroups[group_of(r["classifier_rule"])].append(r)
    w(f"{len(final_misses)} misses, of which {sum(1 for r in final_misses if r['kind'] == 'answer')} are answers to a "
      f"pending question and {sum(1 for r in final_misses if r['confidence'] == 'debatable')} are debatable.")
    w("")
    w("| Group | n | Cases |")
    w("|---|---|---|")
    for group, items in sorted(fgroups.items(), key=lambda kv: -len(kv[1])):
        w(f"| {group} | {len(items)} | " + "; ".join(f"{r['id']} \"{r['text']}\" -> {r['classifier']['intent']}" for r in items) + " |")
    w("")

    # ---------------------------------------------------------------- orchestrator
    w("## Orchestrator routing versus the classifier")
    w("")
    w("The orchestrator reaches a different answer from the bare classifier in three ways, all outside "
      "`intent_classifier.py`:")
    w("")
    diff_final = [r for r in final["rows"] if r["orchestrator"]["routed_intents"] != [r["classifier"]["intent"]]]
    multi = [r for r in diff_final if r["orchestrator"]["multi_agent"]]
    pre = [r for r in diff_final if r["orchestrator"]["pre_empted"]]
    other = [r for r in diff_final if not r["orchestrator"]["multi_agent"] and not r["orchestrator"]["pre_empted"]]
    w(f"- **Multi-agent turns** ({len(multi)} cases): `detect_applicable_intents()` collects every keyword domain in "
      f"the message and `MultiAgentCoordinator` runs all of them, so \"Is drinking coconut water good for recovery?\" "
      f"is answered by Nutrition *and* Recovery. Lenient scoring counts these as correct; strict scoring is where the "
      f"Nutrition and Wound Care columns lose points.")
    w(f"- **Pre-empted turns** ({len(pre)} cases): the RED safety path and the ScopeValidator run before routing. "
      f"\"I can't breathe and my knee wound is worse\" and \"What is the weather like today?\" are the intended cases; "
      f"\"On the other hand my knee feels better\" is deflected as out of scope because `ScopeValidator` reads "
      f"\"hand\" as an unsupported body region (`lam/scope_validator.py`, `_UNSUPPORTED_REGION_LIST`).")
    w(f"- **Patient record and wound context** ({len(other)} case{'s' if len(other) != 1 else ''}): the default patient record lists Paracetamol and "
      f"Enoxaparin, so any message naming them is MEDICATION before the classifier runs (this is why c13's opening "
      f"\"My knee aches a little, I took paracetamol an hour ago.\" stays with Medication through the orchestrator), "
      f"and an explicit wound word gives Wound Care priority over a Pain keyword (\"soreness and some fluid leaking "
      f"near my stitches\").")
    w("")
    w("Noticed while reading the orchestrator, not changed (outside the scope of this task): "
      "`_has_explicit_different_domain()` in `lam/orchestrator.py` uses substring matching, so the Rehab term "
      "\"rom\" matches \"from\" (\"fluid coming from my incision\") and the term \"bath\" matches \"bathroom\"; "
      "a Pain or Recovery follow-up answer that contains \"from\" is treated as an explicit topic switch and loses "
      "its continuation.")
    w("")

    # ---------------------------------------------------------------- experiment
    w("## Step 4 experiment: semantic-first, keywords as tiebreaker (not shipped)")
    w("")
    if exp is None:
        w("No `semantic_first` result file found.")
    else:
        eo = exp["summary"]["overall"]
        w("Behind `SEMANTIC_FIRST` in `lam/intent_classifier.py` (default off; `LAM_SEMANTIC_FIRST=1` switches it on; "
          "the benchmark's `--semantic-first` sets it for one run). Order with the flag on: Sentence-BERT scores "
          "(same intake-cue gate), the semantic winner when score >= 0.35 and margin >= 0.04, the keyword rules as "
          "tiebreaker when the margin is thin (a keyword hit inside the top two wins; a hit outside wins over both; "
          "no keyword keeps the semantic winner), and the keyword rules then the default when confidence is low or "
          "the model is offline. The recorded-medication and medication-context shortcuts still run first.")
        w("")
        w("| | Step B (shipped) | Semantic-first |")
        w("|---|---|---|")
        for key, title in (("classifier", "Classifier"), ("classifier_clear", "Classifier, clear only"),
                           ("classifier_openings", "Classifier, openings only"), ("orchestrator", "Orchestrator (lenient)"),
                           ("orchestrator_strict", "Orchestrator (strict)")):
            w(f"| {title} | {pct(fo[key])} | {pct(eo[key])} ({delta(fo[key], eo[key])}) |")
        w("")
        w("| Agent | Step B classifier | Semantic-first classifier | Step B orchestrator | Semantic-first orchestrator |")
        w("|---|---|---|---|---|")
        for agent in AGENTS:
            if agent not in final["summary"]["per_agent"]:
                continue
            f, e = final["summary"]["per_agent"][agent], exp["summary"]["per_agent"][agent]
            w(f"| {NAME[agent]} | {pct(f['classifier'])} | {pct(e['classifier'])} ({delta(f['classifier'], e['classifier'])}) | "
              f"{pct(f['orchestrator'])} | {pct(e['orchestrator'])} ({delta(f['orchestrator'], e['orchestrator'])}) |")
        w("")
        exp_rows = rows_by_id(exp)
        gained = [r for r in final["rows"] if not r.get("orchestrator_expected") and not r["classifier_correct"]
                  and exp_rows[r["id"]]["classifier_correct"]]
        lost = [r for r in final["rows"] if not r.get("orchestrator_expected") and r["classifier_correct"]
                and not exp_rows[r["id"]]["classifier_correct"]]
        w(f"Cases the experiment gets right that step B misses ({len(gained)}):")
        w("")
        for r in gained:
            e = exp_rows[r["id"]]["classifier"]
            w(f"- {r['id']} \"{r['text']}\": {r['classifier']['intent']} -> {e['intent']} ({e['decision_path']})")
        w("")
        w(f"Cases the experiment loses ({len(lost)}):")
        w("")
        for r in lost:
            e = exp_rows[r["id"]]["classifier"]
            w(f"- {r['id']} \"{r['text']}\" (expected {r['expected']}): {r['classifier']['intent']} -> {e['intent']} "
              f"({e['decision_path']}, top1 {e['top1_intent']} {e['top1_score']:.2f} via {e['matched_prototype']!r})")
        w("")
        hard = [r for r in exp["rows"] if r["source"] == "phase2:benchmark" and not r["classifier_correct"]]
        w(f"`test_phase2_intent.py` hard benchmark assertions that would fail with the flag on: "
          f"{len(hard)}" + (" (" + ", ".join(f'{r["id"]} "{r["text"]}" -> {r["classifier"]["intent"]}' for r in hard) + ")" if hard else "") + ". "
          "`test_multi_agent_orchestration.py` with `LAM_SEMANTIC_FIRST=1`: 1 of 5 fails "
          "(`test_missed_medication_then_wound_handoff`): R043 classifies as pain_symptoms, the orchestrator adds the "
          "classifier's intent to the keyword plan, and the plan becomes [medication, wound_care, pain_symptoms]. "
          "Net: the experiment trades 8 recovered cases for 10 lost ones, mostly symptom-shaped sentences pulled to "
          "the Mental Wellbeing and Pain prototypes (\"put full weight on my operated leg\", \"my incision is "
          "itching\"), and it loses on strict orchestrator routing. Not recommended as is; it would need the "
          "prototype lists reworked first.")
        w("")

    # ---------------------------------------------------------------- tests
    w("## Test suites after the fix")
    w("")
    w("| Suite | Result |")
    w("|---|---|")
    w("| `run_agent_tests.py` (Pain, Recovery, Rehab) | 109 passed |")
    w("| `test_multi_agent_orchestration.py` | 5 passed |")
