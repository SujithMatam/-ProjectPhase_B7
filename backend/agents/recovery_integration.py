# RETRIEVAL QUERY HINTS -- the final turn's LLM call (ChatAgent) retrieves
# with the user_message it is given; a bare continuation reply ("80
# degrees") carries none of the corpus's own vocabulary, so the query is
# augmented with a fixed, metric-specific phrase built from words that
# already appear in the corpus keywords. Never fabricated evidence.
# ============================================================================

_RETRIEVAL_QUERY_HINTS: Dict[str, str] = {
    recovery_logic.ROM_FLEXION_DEGREES: "knee flexion range of motion recovery milestone",
    recovery_logic.ROM_EXTENSION_DEGREES: "knee extension range of motion recovery milestone",
    recovery_logic.MOBILITY_STATUS: "walking aid walker crutches cane walking recovery progress",
    recovery_logic.WALKING_DURATION_MINUTES: "walking recovery progress milestones",
    recovery_logic.STAIRS: "stairs walking recovery progress",
    recovery_logic.HIP_PRECAUTIONS: "hip precautions recovery progress",
    recovery_logic.DAILY_ACTIVITIES: "daily activities recovery milestones",
    recovery_logic.DRIVING: "driving recovery milestones",
    recovery_logic.RETURN_TO_WORK: "return to work recovery",
}


def build_retrieval_query(user_message: str, metric: str) -> str:
    hint = _RETRIEVAL_QUERY_HINTS.get(metric)
    if not hint:
        return user_message
    return f"{user_message} {hint}"


def build_final_retrieval_query(*, surgery_type: str, procedure: str, postop_day: int, metrics: Sequence[str]) -> str:
    joint = "hip" if procedure == "THA" else "knee"
    hints: List[str] = []
    for metric in metrics:
        hint = _RETRIEVAL_QUERY_HINTS.get(metric)
        if hint and hint not in hints:
            hints.append(hint)
    return (
        f"How is my {joint} recovery progressing on day {postop_day} after {surgery_type}, "
        f"and what should I work towards next? {' '.join(hints[:3])}"
    ).strip()


def build_recovery_evidence_from_chunk(chunk) -> "recovery_logic.RecoveryEvidence":
    """Adapt a retrieved chunk into the small RecoveryEvidence view (used
    only for attribution now; the milestone file drives comparisons)."""
    return recovery_logic.RecoveryEvidence(
        source_id=chunk.doc_id,
        procedure=chunk.procedure,
        days_raw=chunk.days,
    )


