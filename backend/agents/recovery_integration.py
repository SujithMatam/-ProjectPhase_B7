def _metric_label(metric: str) -> str:
    return _METRIC_LABELS.get(metric, metric.replace("_", " "))


def confirm_question(metric: str, value: Any, days_ago: int) -> str:
    """Offer a logged value back instead of asking from scratch."""
    when = "today" if days_ago <= 0 else "yesterday"
    if metric == recovery_logic.ROM_FLEXION_DEGREES:
        return f"Your log from {when} says you could bend to {_fmt_num(value)}° -- still about that?"
    if metric == recovery_logic.ROM_EXTENSION_DEGREES:
        return f"Your log from {when} says your extension was {_fmt_num(value)}° -- still about that?"
    return f"Your log from {when} says {_metric_label(metric)} was {value} -- still about that?"


def question_text(metric: str, *, variant: str = "primary", confirm_value: Any = None, confirm_days_ago: int = 0) -> str:
    if variant == "confirm" and confirm_value is not None:
        return confirm_question(metric, confirm_value, confirm_days_ago)
    if variant == "alt":
        return _ALT_QUESTIONS.get(metric, _ASK_QUESTIONS.get(metric, "Could you share more detail about your current recovery status?"))
    return _ASK_QUESTIONS.get(metric, "Could you share more detail about your current recovery status?")


def format_ask_question(
    metric: str,
    *,
    reason_code: Optional[str] = None,
    variation_seed: int = 0,
    variant: str = "primary",
    confirm_value: Any = None,
    confirm_days_ago: int = 0,
) -> str:
    """Patient-facing question for one Recovery field. A plain first ask
    gets no acknowledgment; a retry / clarification / return-to-pending /
    declined confirmation gets a short, natural lead-in rotated by
    `variation_seed`."""
    DRC = recovery_logic.DecisionReasonCode
    if reason_code == DRC.FIELD_UNFIT and metric in _CLARIFY_QUESTIONS:
        return _CLARIFY_QUESTIONS[metric]

    question = question_text(metric, variant=variant, confirm_value=confirm_value, confirm_days_ago=confirm_days_ago)

    if reason_code == DRC.FIELD_UNKNOWN_RETRY_REMAINING:
        ack = _pick(_RETRY_ACK_POOL, variation_seed)
    elif reason_code == DRC.FIELD_AMBIGUOUS:
        ack = _pick(_AMBIGUOUS_ACK_POOL, variation_seed)
    elif reason_code == DRC.FIELD_PENDING:
        ack = _pick(_PENDING_ACK_POOL, variation_seed)
    elif reason_code == DRC.CONFIRM_DECLINED:
        ack = _pick(_DECLINED_ACK_POOL, variation_seed)
    else:
        ack = ""

    return f"{ack} {question}" if ack else question


