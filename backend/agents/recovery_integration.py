def persist_assessment(patient_id: str, state: "recovery_state.RecoverySessionState", *, postop_day: Optional[int]) -> bool:
    """Write the collected flexion / extension / exercise_completed into
    today's `metrics` row via agents/patient_memory.py. Only exact numbers
    are written (a range answer such as "nearly flat" writes nothing for
    that column; "fully flat" is the exact 0°). Returns True on a write."""
    try:
        from agents import patient_memory

        def _numeric(metric: str) -> Optional[float]:
            if not state.is_current(metric):
                return None
            fact = state.get_fact(metric)
            value = fact.value if fact else None
            if isinstance(value, recovery_logic.ValueRange):
                return float(value.low) if value.is_point else None
            if isinstance(value, (int, float)) and not isinstance(value, bool):
                return float(value)
            return None

        exercise: Optional[bool] = None
        if state.is_current(recovery_logic.EXERCISE_COMPLETED):
            fact = state.get_fact(recovery_logic.EXERCISE_COMPLETED)
            if fact is not None and isinstance(fact.value, bool):
                exercise = fact.value

        return patient_memory.write_today_metrics(
            patient_id,
            rom_flexion=_numeric(recovery_logic.ROM_FLEXION_DEGREES),
            rom_extension=_numeric(recovery_logic.ROM_EXTENSION_DEGREES),
            exercise_completed=exercise,
            postop_day=postop_day,
        )
    except Exception as exc:
        print(f"[RECOVERY] metrics persistence failed: {exc}")
        return False


def remaining_indicator(remaining_after_next: int) -> str:
    return progress_indicator(max(remaining_after_next, 0))
