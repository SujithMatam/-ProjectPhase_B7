# ============================================================================
# POSTOPERATIVE-DAY DERIVATION
# ============================================================================
#
# CALENDAR-DATE / TIMEZONE CONVENTION: this project has no per-patient
# timezone metadata, and the Flutter client sends naive local ISO strings.
# The ONE rule applied to every input shape (naive ISO, 'Z' ISO, offset ISO)
# is: take the literal YYYY-MM-DD digits of surgery_date, ignore time-of-day
# and any zone marker, and count calendar days to the SERVER's own local
# date. The surgery date itself is Post-Op Day 1 (project convention, see
# lib/models/patient_user.dart's .clamp(1, 365)). This is only correct when
# the backend host and the patient/app agree on the calendar date -- an
# accepted assumption for this branch; converting naive timestamps to UTC
# would merely guess a timezone, so it is deliberately not done. `today=`
# stays injectable so tests pin a deterministic date.

_DATE_ONLY_RE = re.compile(r"^\s*(\d{4})-(\d{2})-(\d{2})")


def parse_calendar_date(surgery_date_raw: Optional[str]) -> Optional[date]:
    """Literal YYYY-MM-DD of a surgery_date string; None for missing or
    malformed input -- never raises, never guesses a default date."""
    if not surgery_date_raw:
        return None
    match = _DATE_ONLY_RE.match(surgery_date_raw)
    if not match:
        return None
    year, month, day = int(match.group(1)), int(match.group(2)), int(match.group(3))
    try:
        return date(year, month, day)
    except ValueError:
        return None


def derive_effective_postop_day(
    surgery_date_raw: Optional[str],
    *,
    today: Optional[date] = None,
) -> Optional[int]:
    """Server-side, trusted postoperative day. None for a missing /
    malformed / future surgery_date -- callers then call
    state.clear_verified_day(), never fall back to the client's day."""
    surgery_date = parse_calendar_date(surgery_date_raw)
    if surgery_date is None:
        return None
    if today is None:
        today = datetime.now().date()
    day = (today - surgery_date).days + 1
    if day < 1:
        return None
    return day


def log_postop_day_mismatch(
    *, patient_id: str, client_day: Optional[int], server_day: Optional[int], state=None,
) -> bool:
    """The server-derived day is kept; when the client-sent day disagrees
    a WARNING is logged (and printed, like the rest of this codebase's
    diagnostics) -- once per distinct disagreement when `state` is given.
    Returns True iff a mismatch was logged this call."""
    if client_day is None or server_day is None or int(client_day) == int(server_day):
        return False
    pair = (int(client_day), int(server_day))
    if state is not None and getattr(state, "last_mismatch_logged", None) == pair:
        return False
    message = (
        f"[RECOVERY] postop_day mismatch for patient {patient_id}: client sent {client_day}, "
        f"server derived {server_day} from surgery_date -- using the server-derived day"
    )
    _LOG.warning(message)
    print(message)
    if state is not None:
        state.last_mismatch_logged = pair
    return True


