_DEGREE_PATTERN = re.compile(r"\d+(\.\d+)?\s*(degrees|deg|°)", re.IGNORECASE)
_BARE_NUMBER_PATTERN = re.compile(r"^\s*(?:about|around|roughly|approximately|maybe|~)?\s*\d+(?:\.\d+)?\s*[.!]?\s*$", re.IGNORECASE)
_YES_NO_PATTERN = re.compile(
    r"^\s*(?:yes|yeah|yep|yup|no|nope|not really|not quite|not yet|correct|right|that'?s right|still|same|the same|"
    r"about that|still about that|pretty much|i think so|i can|i can'?t|can'?t)\b[\s.!,]*(?:still|about|that|same|the same)?[\s.!]*$",
    re.IGNORECASE,
)
_FLEXION_WORDS = ("bend", "flex", "flexion", "bent")
_EXTENSION_WORDS = ("straighten", "extend", "extension", "straight", "flat")
_MOBILITY_WORDS = ("walker", "cane", "crutches", "crutch", "frame", "stick", "independent", "independently", "without a", "on my own", "no aid")
_DURATION_WORDS = ("minute", "minutes", "mins", "min ", "hour", "half an hour", "more than ten", "less than ten", "over ten", "under ten", "walk")
_STAIRS_WORDS = ("stair", "stairs", "steps", "step", "one at a time", "foot over foot", "rail", "banister", "not yet")
_PRECAUTION_WORDS = ("precaution", "precautions", "90 degrees", "right angle", "cross", "low chair", "following", "keeping")
_DONT_KNOW_WORDS = ("don't know", "dont know", "not sure", "no idea", "haven't measured")
_SAME_AS_YESTERDAY_PHRASE = "same as yesterday"
_PAIN_WORD_RE = re.compile(r"\bpain\b", re.IGNORECASE)
_PAIN_SCALE_RE = re.compile(r"\b\d{1,2}\s*(?:/|out of)\s*10\b", re.IGNORECASE)


def message_plausibly_answers_pending_field(
    message: str,
    pending_field: str,
    *,
    variant: Optional[str] = None,
    confirm_pending: bool = False,
) -> bool:
    """
    Narrow, deterministic check: does `message` plausibly answer the ONE
    SPECIFIC Recovery field currently pending? NOT a general intent
    classifier -- it only recognises a small, field-scoped set of answer
    shapes (plus the universal "I don't know" / "same as yesterday" non-
    answers, a bare number for a numeric field, and a yes/no when the
    pending question was yes/no-shaped: a confirmation offer, the simpler
    extension question, stairs or hip precautions). Anything else (wound,
    medication, emergency, unrelated topics) returns False so fresh intent
    classification runs.
    """
    lower = (message or "").strip().lower()
    if not lower:
        return False

    if _SAME_AS_YESTERDAY_PHRASE in lower:
        return True
    if any(phrase in lower for phrase in _DONT_KNOW_WORDS):
        return True

    yes_no = bool(_YES_NO_PATTERN.match(lower))
    if yes_no and (
        confirm_pending
        or pending_field in (recovery_logic.STAIRS, recovery_logic.HIP_PRECAUTIONS, recovery_logic.ROM_EXTENSION_DEGREES)
        or (variant == "alt" and pending_field in recovery_logic.NUMERIC_FIELDS)
    ):
        return True

    if pending_field in recovery_logic.NUMERIC_FIELDS and (
        _BARE_NUMBER_PATTERN.match(lower) or recovery_logic.loose_number(lower) is not None
    ):
        # A bare or short single-number reply ("80", "it's about 85 now")
        # answers the one numeric question that is open.
        return True

    if (
        variant == "alt" and pending_field == recovery_logic.WALKING_DURATION_MINUTES
        and re.match(r"^\s*(?:yes,?\s*|no,?\s*)?(?:more|less|longer|shorter|over|under|above|below)\b", lower)
    ):
        return True

    if pending_field in recovery_logic.ROM_FIELDS:
        if _DEGREE_PATTERN.search(lower):
            return True
        cue_words = _FLEXION_WORDS if pending_field == recovery_logic.ROM_FLEXION_DEGREES else _EXTENSION_WORDS
        return any(word in lower for word in cue_words)

    if pending_field == recovery_logic.MOBILITY_STATUS:
        return any(word in lower for word in _MOBILITY_WORDS)

    if pending_field == recovery_logic.WALKING_DURATION_MINUTES:
        return any(word in lower for word in _DURATION_WORDS)

    if pending_field == recovery_logic.STAIRS:
        return any(word in lower for word in _STAIRS_WORDS)

    if pending_field == recovery_logic.HIP_PRECAUTIONS:
        return any(word in lower for word in _PRECAUTION_WORDS)

    if pending_field == recovery_logic.PAIN_SCORE:
        return bool(_PAIN_WORD_RE.search(lower)) or bool(_PAIN_SCALE_RE.search(lower))

    return False


def check_recovery_continuation(
    *,
    patient_id: str,
    surgery_date_raw: Optional[str],
    procedure: str,
    user_message: str,
) -> bool:
    """
    The orchestrator's ONLY entry point for Recovery continuation. True
    only when an EXISTING episode (peek_state, exact key, never created
    here) has a real pending_field and the message plausibly answers THAT
    field. Never uses "Recovery was the last agent" as a signal; never
    mutates state.
    """
    state = recovery_state.peek_state(
        patient_id=patient_id, surgery_date_raw=surgery_date_raw, procedure=procedure,
    )
    if state is None or state.pending_field is None:
        return False
    return message_plausibly_answers_pending_field(
        user_message, state.pending_field,
        variant=state.pending_variant, confirm_pending=state.pending_confirm_value is not None,
    )


